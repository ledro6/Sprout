package com.ledro6.sprout.model

/**
 * Слова приложения, которые понятны не всем, — с пояснением простыми
 * словами. Видны по «?» рядом со словом и списком в «Словарике». Где
 * Android устроен иначе, чем iPhone (замок, сканер), — свои строки.
 */
enum class Term {
    AR, MODEL, MOISTURE, PERIOD, SEASONS, RHYTHM, FEEDING, REPOTTING,
    REMINDERS, PARALLAX, SWAY, WAVE, FROLIC, LOCK, TRIP, ACCURACY,
    STREAK, ORRERY, PARADE;

    val title: String
        get() = when (this) {
            AR -> Lang.text("AR — дополненная реальность")
            MODEL -> Lang.text("Модель растения")
            MOISTURE -> Lang.text("Влажность")
            PERIOD -> Lang.text("Срок полива")
            SEASONS -> Lang.text("Время года")
            RHYTHM -> Lang.text("Ритм полива")
            FEEDING -> Lang.text("Подкормка")
            REPOTTING -> Lang.text("Пересадка")
            REMINDERS -> Lang.text("Напоминание о поливе")
            PARALLAX -> Lang.text("Узор за наклоном")
            SWAY -> Lang.text("Фигурки плывут порознь")
            WAVE -> Lang.text("Волна")
            FROLIC -> Lang.text("Кутерьма")
            LOCK -> Lang.text("Замок")
            TRIP -> Lang.text("Уезжаю")
            ACCURACY -> Lang.text("Точность полива")
            STREAK -> Lang.text("Череда")
            ORRERY -> Lang.text("Планетарий")
            PARADE -> Lang.text("Парад")
        }

    val meaning: String
        get() = when (this) {
            AR -> Lang.text(
                "Камера показывает вашу комнату, а приложение ставит в неё объёмное растение. " +
                    "Его можно повернуть, растянуть и полить лейкой.",
            )
            MODEL -> Lang.text(
                "Объёмная копия растения для AR. Модели видов уже лежат в приложении, а свою " +
                    "можно придумать по фото — кнопка «Модель» на экране растения.",
            )
            MOISTURE -> Lang.text(
                "Сколько воды осталось в земле. После полива — сто процентов, потом земля " +
                    "подсыхает. Чем суше, тем ярче тень вокруг карточки.",
            )
            PERIOD -> Lang.text(
                "Раз в сколько дней растение поливают — примерно за столько земля высыхает. " +
                    "Меняется в настройках растения.",
            )
            SEASONS -> Lang.text(
                "Зимой земля сохнет медленнее, летом — быстрее. Если включено, срок полива " +
                    "подстраивается сам.",
            )
            RHYTHM -> Lang.text(
                "Если вы поливаете раньше срока, приложение заметит и предложит сделать срок короче.",
            )
            FEEDING -> Lang.text(
                "Удобрение, разведённое в воде для полива. Нужно раз в несколько недель, пока " +
                    "растение растёт.",
            )
            REPOTTING -> Lang.text(
                "Переезд в горшок побольше со свежей землёй. Обычно раз в год-два, весной.",
            )
            REMINDERS -> Lang.text(
                "Уведомление на телефон, когда земля у растения подсохла ниже выбранного порога.",
            )
            PARALLAX -> Lang.text(
                "Узор на фоне чуть сдвигается, когда вы наклоняете телефон, — будто лежит " +
                    "глубже экрана.",
            )
            SWAY -> Lang.text(
                "При наклоне каждая фигурка узора движется со своей скоростью, будто плывёт в воде.",
            )
            WAVE -> Lang.text(
                "После полива по узору бежит цветная волна — так видно, что полив засчитан.",
            )
            FROLIC -> Lang.text(
                "Потрясите телефон — фигурки узора разлетятся и соберутся снова. Просто для радости.",
            )
            LOCK -> Lang.text(
                "Сад открывается только по отпечатку пальца, лицу или коду разблокировки " +
                    "телефона — чужие не посмотрят.",
            )
            TRIP -> Lang.text(
                "План на отпуск: полить всех перед отъездом и отправить соседу памятку, кого " +
                    "и когда поливать.",
            )
            ACCURACY -> Lang.text(
                "Сколько воды оставалось в земле, когда вы поливали. Вовремя — когда карточка " +
                    "светится оранжевым: в земле 20–40%.",
            )
            STREAK -> Lang.text(
                "Сколько дней подряд вы поливали хоть одно растение. Пропущенный день начинает " +
                    "счёт заново.",
            )
            ORRERY -> Lang.text(
                "Сад как солнечная система: растение — планета, круг — срок полива. Дошла до " +
                    "ворот наверху — пора поливать.",
            )
            PARADE -> Lang.text(
                "День, когда воды попросят сразу три растения и больше, — удобно полить всех " +
                    "за один заход.",
            )
        }
}

