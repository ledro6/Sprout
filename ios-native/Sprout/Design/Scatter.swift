/// Разброс частиц: 0…1 по номеру частицы и соли. Одно и то же на каждом
/// кадре — частица не мигает, — но соли между собой не связаны. Прежняя
/// линейная смесь делала все свойства частицы одним числом со сдвигом:
/// задержка, скорость и место шли в ногу, и конфетти летели одной палкой.
/// Здесь — перемешивание SplitMix64.
enum Scatter {
    static func unit(_ index: Int, _ salt: Int) -> Double {
        let a = UInt64(truncatingIfNeeded: index) &* 0x9E37_79B9_7F4A_7C15
        let b = UInt64(truncatingIfNeeded: salt) &* 0xD1B5_4A32_D192_ED03
        var z: UInt64 = a ^ b
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        z ^= z >> 31
        return Double(z >> 11) / 9_007_199_254_740_992
    }
}
