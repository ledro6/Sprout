import SwiftUI

extension Shape {
    /// Ореол вокруг плашки: залитая форма, размытая, с вырезанным
    /// силуэтом самой плашки.
    ///
    /// Вырез обязателен. Заливка плашки полупрозрачная, и без выреза
    /// ореол просвечивал бы сквозь неё, крася плашку изнутри, — в макете
    /// у теней по той же причине стоит «не рисовать под самим слоем».
    /// Обводкой это не заменить: обводка стоит серединой на кромке, и её
    /// внутренняя половина оказывается под плашкой.
    func sproutHalo(_ color: Color, blur: CGFloat,
                    offsetY: CGFloat = 0) -> some View {
        ZStack {
            fill(color)
                .blur(radius: blur)
                .offset(y: offsetY)
            fill(.black)
                .blendMode(.destinationOut)
        }
        .compositingGroup()
    }
}

extension View {
    /// Материал плашек макета: вуаль белым 10% и мягкая тень под ней.
    ///
    /// В макете каждая плашка — фото растения, карточка, панель со
    /// сведениями — устроена одинаково: заливка белым 10% плюс стеклянный
    /// эффект. Сквозь такую заливку фоновый узор проходит почти
    /// нетронутым, и плашка читается вуалью, а не листом бумаги.
    ///
    /// Системного стекла здесь нет намеренно. Стекло размывает и
    /// подсвечивает то, что за ним, а за плашками — белый фон с очень
    /// бледным узором; любой такой материал сводит его к сплошному
    /// белому, и на телефоне плашки выходили белыми плитами, хотя вокруг
    /// узор виден. Стекло осталось там, где ему есть что преломлять:
    /// таб-бар, поиск, панель навигации.
    ///
    /// Тень нельзя вешать через `.shadow`: она уводит вью в отдельный
    /// слой. Поэтому она рисуется в `.background`, позади вуали.
    func sproutPlate(in shape: some Shape) -> some View {
        background { shape.fill(Palette.plateFill) }
            .background {
                shape.sproutHalo(Palette.shadow,
                                 blur: Metrics.plateShadowBlur,
                                 offsetY: Metrics.plateShadowY)
            }
            // Заливка сама по себе не ловит нажатия — очерчиваем плашку,
            // иначе тап проходит только по картинке и подписям.
            .contentShape(shape)
    }
}
