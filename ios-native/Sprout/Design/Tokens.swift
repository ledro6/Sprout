import SwiftUI
import UIKit

/// Значения из макета Figma «орпи». Выгружены tool/figma_extract.py и
/// отранжированы по частоте — то, что встречается в макете десятки раз,
/// и есть токен.
///
/// Макет нарисован только в светлой теме. Тёмная — не его инверсия, а
/// пересчёт: белое становится серым, а не чёрным. На чёрном стеклянные
/// плашки не за что зацепить взглядом — их материал светлеет от того, что
/// под ним, и поверх чёрного он остаётся чёрным; узор пропадает там же.
enum Palette {
    /// Цвет, меняющийся вместе с темой системы.
    ///
    /// Через UIKit, а не через набор цветов в ассетах: так обе половины
    /// лежат в одном файле рядом, и прямо в строке видно, во что
    /// превращается оттенок. По ассетам за этим пришлось бы ходить
    /// поодиночке, открывая каждый цвет отдельно.
    private static func dual(_ light: Color, _ dark: Color) -> Color {
        Color(UIColor { traits in
            UIColor(traits.userInterfaceStyle == .dark ? dark : light)
        })
    }

    private static func rgb(_ r: Double, _ g: Double, _ b: Double) -> Color {
        Color(red: r / 255, green: g / 255, blue: b / 255)
    }

    /// Фон приложения: белый в светлой теме, серый в тёмной.
    static let background = dual(.white, rgb(43, 46, 44))

    /// Основной текст. В тёмной теме не чистый белый: на сером он звенит,
    /// и читать длинные строки таким тяжело.
    static let ink = dual(.black, rgb(238, 241, 237))

    /// Узор из ростков и капель, #CFF8C9. Цвет один, меняется доля.
    ///
    /// Доля подобрана так, чтобы узор в обеих темах отходил от фона
    /// одинаково: на белом 30% дают разницу около 5% яркости, на сером
    /// столько же даёт 8% — светлое на тёмном заметнее, чем светлое на
    /// светлом, и той же трети там было бы слишком много.
    static let pattern = dual(rgb(207, 248, 201).opacity(0.3),
                              rgb(207, 248, 201).opacity(0.08))

    /// Системный синий iOS: выбранная комната и активная вкладка. В
    /// тёмной теме светлее — так же, как системный синий у самой iOS.
    static let accent = dual(rgb(0, 136, 255), rgb(74, 168, 255))

    /// Зелёный логотипа. Одинаков в обеих темах: он лежит на своей
    /// светло-зелёной плашке, а она не меняется.
    static let green = rgb(55, 181, 81)

    /// Светло-зелёная плашка логотипа.
    static let greenSoft = rgb(198, 250, 183)

    /// Голубой капли на логотипе.
    static let water = rgb(71, 181, 228)

    /// Тень всех плашек макета: #0000001F. У карточки на главном экране
    /// в данных стоит вчетверо плотнее, но это выброс: в самом рендере
    /// под её нижней кромкой фон темнеет ровно настолько же, насколько
    /// под остальными плашками, — на 8%, сходя на нет за 25 pt.
    ///
    /// В тёмной теме плотнее: на сером фоне тень в 12% не видно вовсе.
    static let shadow = dual(.black.opacity(0.12), .black.opacity(0.45))

    /// Заливка плашек — вуаль, сквозь которую виден узор. В тёмной теме
    /// чуть плотнее: плашка должна оставаться светлее своего фона, а
    /// разница между серым и серым тоньше, чем между белым и белым.
    static let plateFill = dual(.white.opacity(0.1), .white.opacity(0.14))

    /// Тревожное свечение — полив завтра: #FF000066. В тёмной теме ярче:
    /// красный на сером глуше, чем на белом.
    static let thirsty = dual(.red.opacity(0.4), .red.opacity(0.5))

    /// То же в критической стадии — полив сегодня: #FF000099.
    static let thirstyNow = dual(.red.opacity(0.6), .red.opacity(0.72))
}

/// Начертания. Шрифт намеренно не задан именем: система подставит SF Pro,
/// на котором макет и нарисован. Вес 590 в Figma — это semibold, 510 — medium.
enum Typography {
    /// Кнопка выбора комнаты — 18/28 semibold.
    static let room = Font.system(size: 18, weight: .semibold)

    /// Имя растения и влажность на карточке — 16/19 medium.
    static let cardTitle = Font.system(size: 16, weight: .medium)

    /// «Следующий полив…» — 10/12 regular.
    static let cardCaption = Font.system(size: 10, weight: .regular)

    /// Заголовок экрана растения — 21/28 semibold.
    static let navTitle = Font.system(size: 21, weight: .semibold)

    /// Строка списка на экране растения — 17/28 semibold.
    static let detail = Font.system(size: 17, weight: .semibold)

    /// Название приложения на плашке под чёлкой.
    static let wordmark = Font.system(size: 15, weight: .regular)
}

/// Размеры и отступы макета в логических пикселях.
enum Metrics {
    /// Боковое поле контента на экране растения — из макета.
    static let margin: CGFloat = 33

    /// Боковое поле разделов со списками. Не из макета: заголовок здесь
    /// системный, и содержимое должно вставать по его левому краю, а не
    /// по макетным 33.
    static let contentMargin: CGFloat = 20

    /// Промежутки между карточками: по горизонтали 36, по вертикали 25.
    static let gutterH: CGFloat = 36
    static let gutterV: CGFloat = 25

    /// Скругление карточки и внутреннее поле.
    static let cardRadius: CGFloat = 26
    static let cardPadding: CGFloat = 11

    /// Тень плашки: смещение из макета, размытие подобрано под рендер.
    static let plateShadowY: CGFloat = 8
    static let plateShadowBlur: CGFloat = 7

    /// Размытие тревожного свечения. Подобрано под рендер макета: там у
    /// кромки красного примерно 17%, на 10 pt в сторону — 10%, на 24 —
    /// 2.5%. Ореол отдаёт у кромки половину своего цвета, дальше сходит
    /// по гауссиане, и с сигмой 14 от #FF000066 получается ровно это.
    static let glowBlur: CGFloat = 14

    /// Плашка с логотипом от верха экрана. В макете 19, здесь 5: при 19
    /// нижняя треть капсулы вылезала из-под чёлки и читалась поломкой, а
    /// с 5 она целиком помещается в вырез. Прицел по чёлке iPhone 13 Pro
    /// — она кончается на 33; у телефонов с островом он начинается ниже,
    /// и там плашка выглянет над ним.
    static let badgeTop: CGFloat = 5

    /// Растяжка под закреплённой строкой комнаты: полупрозрачная, чтобы
    /// сквозь неё читался узор, как сквозь панель в мессенджерах.
    ///
    /// Ровная часть накрывает саму строку, сход — то, что подъезжает под
    /// неё снизу. Выше строки растяжка не уходит: там стоит заголовок
    /// раздела, и накрытый ею он читался почти белым. Совсем прозрачной
    /// её тоже не сделать — карточки под строкой не должны просвечивать
    /// призраком.
    static let headerWashOpacity: CGFloat = 0.9
    static let headerWashFade: CGFloat = 32

    /// Насколько сход свисает ниже строки комнаты: его длина минус те
    /// 13 pt, что пустуют у кнопки под подписью (её 44 pt — площадь
    /// нажатия, сама подпись занимает 18). На столько же отодвинуты
    /// карточки — тогда сход кончается ровно там, где они начинаются.
    static let headerWashDrop: CGFloat = headerWashFade - 13

    /// Растяжки поверх узора: полоса 166 pt, сплошной фон до 40%.
    static let washHeight: CGFloat = 166
    static let washStop: CGFloat = 0.4
}
