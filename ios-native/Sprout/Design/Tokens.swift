import SwiftUI
import UIKit

/// Значения из макета Figma «орпи». Выгружены tool/figma_extract.py и
/// отранжированы по частоте — то, что встречается в макете десятки раз,
/// и есть токен.
///
/// Макет нарисован только в светлой теме. Тёмная — не его инверсия, а
/// пересчёт: белое становится серым, а не чёрным. На чёрном стеклянные
/// плашки не за что зацепить взглядом — их материал светлеет от того, что
/// под ним, и поверх чёрного он остаётся чёрным; узор пропадает там же.
enum Palette {
    /// Цвет, меняющийся вместе с темой системы.
    ///
    /// Через UIKit, а не через набор цветов в ассетах: так обе половины
    /// лежат в одном файле рядом, и прямо в строке видно, во что
    /// превращается оттенок. По ассетам за этим пришлось бы ходить
    /// поодиночке, открывая каждый цвет отдельно.
    private static func dual(_ light: Color, _ dark: Color) -> Color {
        Color(UIColor { traits in
            UIColor(traits.userInterfaceStyle == .dark ? dark : light)
        })
    }

    private static func rgb(_ r: Double, _ g: Double, _ b: Double) -> Color {
        Color(red: r / 255, green: g / 255, blue: b / 255)
    }

    /// Фон приложения: белый в светлой теме, серый в тёмной.
    static let background = dual(.white, rgb(43, 46, 44))

    /// Основной текст. В тёмной теме не чистый белый: на сером он звенит,
    /// и читать длинные строки таким тяжело.
    static let ink = dual(.black, rgb(238, 241, 237))

    /// Приветственный экран: фон и текст на нём.
    ///
    /// Своя пара, а не общая. Экран этот фирменный: в макете он зелёный в
    /// обеих темах — светлая мякоть #CFF8C9 и тёмная хвоя #12360D, — и
    /// текст на нём чистый чёрный и чистый белый, а не приглушённые
    /// чернила остального приложения.
    static let welcome = dual(rgb(207, 248, 201), rgb(18, 54, 13))
    static let welcomeInk = dual(.black, .white)

    /// Системный синий iOS: выбранная комната и активная вкладка. В
    /// тёмной теме светлее — так же, как системный синий у самой iOS.
    static let accent = dual(rgb(0, 136, 255), rgb(74, 168, 255))

    /// Зелёный логотипа. Одинаков в обеих темах: он лежит на своей
    /// светло-зелёной плашке, а она не меняется.
    static let green = rgb(55, 181, 81)

    /// Светло-зелёная плашка логотипа.
    static let greenSoft = rgb(198, 250, 183)

    /// Голубой капли на логотипе.
    static let water = rgb(71, 181, 228)

    /// Цвет фигурки узора: от цвета покоя до цвета волны полива.
    /// Ноль — покой, единица — гребень. Оттенки выбираются в настройках,
    /// см. `Tint`.
    ///
    /// Доли задаёт не оттенок, а место. В покое узор кладётся в 42% на
    /// белом и в 8% на сером: светлое на тёмном заметнее, чем светлое на
    /// светлом, и 8% там дают ту же разницу с фоном, что и 42% на белом.
    /// В светлой теме доля с тех пор поднята с 30%: под стеклом плашек
    /// узор в треть силы читался бледнее, чем в макете, где стекла над
    /// ним нет.
    ///
    /// Волна берётся плотнее покоя — 46% и 20%. Плотнее обязательно: узор
    /// держится еле заметным нарочно, но всплеск это не фон, а событие, и
    /// взятый той же долей он читался бы не вспышкой, а выцветанием.
    static func pattern(_ base: Tint, wave: Tint, splash level: Double)
        -> Color {
        let k = min(max(level, 0), 1)
        return dual(blend(ink(base.pale, restLight),
                          ink(wave.vivid, splashLight), k),
                    blend(ink(base.pale, restDark),
                          ink(wave.vivid, splashDark), k))
    }

    /// Свечение вокруг фигурки на гребне волны.
    ///
    /// Своя доля, а не та же: свечение размывается, и взятое долей самой
    /// волны оно после размытия не читалось бы вовсе. Растёт вместе с
    /// цветом — на покое его нет.
    static func glow(_ wave: Tint, level: Double) -> Color {
        let k = min(max(level, 0), 1)
        return dual(colour(wave.vivid, glowLight * k),
                    colour(wave.vivid, glowDark * k))
    }

    /// Кружок оттенка в настройках. Насыщенной ипостасью: выбирают
    /// оттенок, а не силу, и бледный кружок на плашке было бы не
    /// разглядеть.
    static func swatch(_ tint: Tint) -> Color { colour(tint.vivid, 1) }

    private static let restLight = 0.42
    private static let restDark = 0.08
    private static let splashLight = 0.46
    private static let splashDark = 0.2
    private static let glowLight = 0.5
    private static let glowDark = 0.38

    private typealias Ink = (r: Double, g: Double, b: Double, a: Double)

    private static func ink(_ c: Channels, _ a: Double) -> Ink {
        (c.red, c.green, c.blue, a)
    }

    private static func colour(_ c: Channels, _ a: Double) -> Color {
        Color(red: c.red / 255, green: c.green / 255, blue: c.blue / 255)
            .opacity(a)
    }

    private static func blend(_ from: Ink, _ to: Ink, _ k: Double) -> Color {
        let mix = { (a: Double, b: Double) in a + (b - a) * k }
        return Color(red: mix(from.r, to.r) / 255,
                     green: mix(from.g, to.g) / 255,
                     blue: mix(from.b, to.b) / 255)
            .opacity(mix(from.a, to.a))
    }

    /// Тревожная тень под карточкой, пока влаги от 40 до 20 процентов.
    /// В тёмной теме светлее: цветное на сером глуше, чем на белом.
    static let warn = dual(rgb(255, 149, 0), rgb(255, 169, 46))

    /// Она же ниже двадцати процентов. Силу тени эти цвета не задают — её
    /// считает сама карточка из влажности, и растёт она с каждым
    /// процентом.
    static let alarm = dual(rgb(255, 59, 48), rgb(255, 92, 82))
}

/// Начертания. Шрифт намеренно не задан именем: система подставит SF Pro,
/// на котором макет и нарисован. Вес 590 в Figma — это semibold, 510 — medium.
/// Шрифты.
///
/// Заданы стилями системы, а не размерами в пунктах. Размер в пунктах
/// глух к настройке «Размер текста»: у кого она поднята, у того всё
/// приложение оставалось бы мелким. Стиль же система масштабирует сама, и
/// вместе с размером ведёт межстрочное расстояние и трекинг — руками это
/// не повторить.
///
/// Числа макета при этом сместились на пункт-другой: ближайший системный
/// стиль вместо 18 даёт 17, вместо 21 — 20, вместо 10 — 11. Это верный
/// размен: макет рисовался в одном масштабе, а телефон бывает настроен
/// на любой.
enum Typography {
    /// Кнопка выбора комнаты — в макете 18 semibold, ближайший стиль 17.
    /// На главном экране размер берётся не отсюда: там кнопка дорастает
    /// при прокрутке до заголовка, и размер перебирается плавно.
    static let room = Font.system(.headline)

    /// Имя растения и влажность на карточке — 16 medium.
    static let cardTitle = Font.system(.callout, weight: .medium)

    /// «Следующий полив…» — в макете 10 regular, ближайший стиль 11.
    static let cardCaption = Font.system(.caption2)

    /// Заголовок экрана растения — в макете 21 semibold, стиль 20.
    static let navTitle = Font.system(.title3, weight: .semibold)

    /// Строка списка на экране растения — 17 semibold.
    static let detail = Font.system(.body, weight: .semibold)

    /// Название приложения на плашке под чёлкой. Единственный шрифт,
    /// который за системой не идёт: плашка — знак, нарисованный в макете
    /// целиком, с капсулой известной высоты. Выросший в ней текст не
    /// прочитался бы лучше, а капсулу разорвал бы.
    static let wordmark = Font.system(size: 15, weight: .regular)

    /// Приветствие на заставке. В макете строка 240 pt на две строки
    /// высотой 68 — то есть около 28 на строку, ближайший стиль так и
    /// зовётся.
    static let welcome = Font.system(.title, weight: .bold)

    /// Подпись над плашкой настроек — «Оформление», «Полив». Мельче
    /// строки и не чернилами, а вполсилы: она называет группу, а не
    /// говорит что-то сама.
    static let groupTitle = Font.system(.footnote, weight: .semibold)

    /// Строка настройки и пояснение под ней.
    static let settingRow = Font.system(.body)
    static let settingNote = Font.system(.footnote)

    /// Подпись на кнопке выбора — теме, пороге. Мельче строки: их в ряду
    /// три-четыре, и каждой достаётся четверть ширины.
    static let pill = Font.system(.subheadline, weight: .medium)

    /// Размер кнопки комнаты в покое и её же, доросшей до заголовка.
    /// Числами, а не шрифтами: между ними идёт плавный перебор.
    static let roomSize: CGFloat = 17
    static let roomGrown: CGFloat = 34
}

/// Размеры и отступы макета в логических пикселях.
enum Metrics {
    /// Боковое поле контента на экране растения — из макета.
    static let margin: CGFloat = 33

    /// Боковое поле разделов со списками. Не из макета: заголовок здесь
    /// системный, и содержимое должно вставать по его левому краю, а не
    /// по макетным 33.
    static let contentMargin: CGFloat = 20

    /// Промежутки между карточками: по горизонтали 36, по вертикали 25.
    static let gutterH: CGFloat = 36
    static let gutterV: CGFloat = 25

    /// Скругление карточки и внутреннее поле.
    static let cardRadius: CGFloat = 26
    static let cardPadding: CGFloat = 11

    /// Тень плашки: смещение из макета, размытие подобрано под рендер.
    static let plateShadowY: CGFloat = 8
    static let plateShadowBlur: CGFloat = 7

    /// Размытие тревожного свечения. Подобрано под рендер макета: там у
    /// кромки красного примерно 17%, на 10 pt в сторону — 10%, на 24 —
    /// 2.5%. Ореол отдаёт у кромки половину своего цвета, дальше сходит
    /// по гауссиане, и с сигмой 14 от #FF000066 получается ровно это.
    static let glowBlur: CGFloat = 14

    /// Сила тревожной тени: у порога в 40% еле заметна, у сухой земли
    /// полная. Между ними перебирается плавно — на этом и держится «чем
    /// суше, тем ярче».
    static let glowFaint = 0.18
    static let glowFull = 0.62

    /// Плашка с логотипом от верха экрана. В макете 19, здесь 5: при 19
    /// нижняя треть капсулы вылезала из-под чёлки и читалась поломкой, а
    /// с 5 она целиком помещается в вырез. Прицел по чёлке iPhone 13 Pro
    /// — она кончается на 33; у телефонов с островом он начинается ниже,
    /// и там плашка выглянет над ним.
    static let badgeTop: CGFloat = 5

    /// Растяжка под закреплённой строкой комнаты: от самого верха экрана
    /// до конца строки, дальше сход в прозрачность.
    ///
    /// Верхнего края у неё нет — он уведён за край экрана. Начинаясь у
    /// строки комнаты, растяжка шла поперёк экрана заметной чертой, и
    /// избавиться от черты можно только так: увести её туда, где её не
    /// видно.
    ///
    /// Заголовок она при этом не глушит: в покое её нет вовсе, а
    /// проступает она по мере прокрутки — ровно тогда, когда под строку
    /// начинают заезжать карточки, а заголовок уже уходит.
    ///
    /// Сплошная, без просвета. Под ней проходит и строка состояния, а
    /// призрак карточки под часами читался бы поломкой. Узора она при
    /// этом не съедает: в покое растяжки нет вовсе, а узор у него всего
    /// 8% плотности — сквозь даже полупрозрачную его было не видно.
    static let headerWashOpacity: CGFloat = 1
    static let headerWashFade: CGFloat = 32

    /// Насколько сход свисает ниже строки комнаты: его длина минус те
    /// 13 pt, что пустуют у кнопки под подписью (её 44 pt — площадь
    /// нажатия, сама подпись занимает 18). На столько же отодвинуты
    /// карточки — тогда сход кончается ровно там, где они начинаются.
    static let headerWashDrop: CGFloat = headerWashFade - 13

    /// Всплеск фигурки узора: какую долю всей волны он занимает,
    /// насколько фигурка раздаётся на гребне и насколько поджимается
    /// перед ним и после него.
    ///
    /// Доля не полная: остаток — то время, за которое волна доходит до
    /// дальних фигурок. Размах и длительность у всех одинаковы, разное у
    /// них только время прихода — потому волна и читается кольцом,
    /// расходящимся от нажатия.
    ///
    /// Окно широкое: волна проходит за него три с половиной сотни
    /// пунктов — семь с половиной делений сетки. Столько рядов в движении
    /// разом, и идут они не поодиночке, а полосами: два с половиной ряда
    /// поджатых, столько же поднявшихся, за ними снова поджатые. Волна от
    /// этого читается ходом полос, а не перебором рядов по очереди.
    ///
    /// Числа сырые: их ещё умножает и оболочка кривой, у которой ямка
    /// глубиной 0.5625 от единицы, и плавный переход между ними. На деле
    /// выходит 1.15 на гребне и 0.66 в ямке — полосы отличаются в три
    /// четверти раза.
    ///
    /// Разницу набирает почти вся ямка, и это не выбор вкуса. Гребень
    /// упёрся в потолок: в широком окне соседний ряд поднимается вместе с
    /// ним, а не поджимается против него, — то есть складываются два
    /// поднявшихся, а не поднявшийся с поджатым. Их половины дают ровно
    /// 46.68 pt при шаге ряда 46.68, впритык и без нахлёста. Ямке же
    /// упираться не во что: поджатым фигуркам смыкаться нечем.
    static let popSpan = 0.28
    static let popAmp = 0.15
    static let popDip = 0.62

    /// Насколько плавно размах переходит в поджим у нуля.
    ///
    /// Раньше не переходил вовсе: по знаку выбирался тот множитель или
    /// этот. Значение на стыке от этого не прыгало, а наклон прыгал —
    /// вчетверо, трижды за проход, — и фигурка на возврате к своему
    /// размеру будто спотыкалась. Плавный переход снимает излом: вторая
    /// производная на стыке падает с пяти тысяч восьмисот до сотни.
    ///
    /// Ширина перехода — доля размаха. Уже — возвращается ступенька;
    /// шире — поджим подмешивается в подъём соседнего ряда, а тот и так
    /// впритык к соседу по сетке.
    static let popBlend = 0.3

    /// Всходы узора при запуске: какую долю всходов занимает одна
    /// фигурка. Остаток — время, за которое очередь обходит экран снизу
    /// вверх. Доля большая: фигурки должны идти внахлёст, иначе вместо
    /// всходов выйдет бегущая строка.
    static let bloomSpan = 0.38

    /// На сколько пунктов волна уходит за отведённое ей время. Больше
    /// диагонали экрана: до дальнего угла она добирается, даже если
    /// нажали в противоположный. От карточки посреди сетки волна
    /// докатывается до краёв заметно раньше — как и положено ряби.
    static let waveReach: CGFloat = 900

    /// Заставка: отступ приветствия от безопасной зоны и высота
    /// логотипа. В макете приветствие стоит на 110 при строке состояния
    /// в 62, а логотип занимает 352 из 874 по высоте и стоит ровно
    /// посередине экрана.
    static let welcomeTop: CGFloat = 48
    static let welcomeLogo: CGFloat = 342

    /// Кнопка в верхней панели: столько же, сколько системная капсула
    /// рядом с ней. Своей капсула стала ради проступания — общую панель
    /// рисует сама, и размытие её не берёт.
    static let barButton: CGFloat = 44

    /// Из какого размытия проступает верхняя панель на экране растения.
    /// Достаточно, чтобы буквы в начале не читались вовсе, — иначе это
    /// не проступание, а просто затемнение.
    static let chromeBlur: CGFloat = 12

    /// Размах параллакса: на столько узор отъезжает от середины в
    /// каждую сторону при наклоне телефона. Меньше шага сетки узора
    /// (89 × 47) — движение должно читаться подкладкой, а не ездой.
    static let parallax: CGFloat = 14

    /// Настройки: промежуток между группами, поля внутри плашки,
    /// расстояние между строками в ней и скругление самой плашки.
    ///
    /// Скругление то же, что у карточки растения: плашки во всём
    /// приложении одного покроя, и настройки не исключение.
    static let groupGap: CGFloat = 26
    static let groupPadding: CGFloat = 16
    static let rowGap: CGFloat = 14

    /// Ряд кнопок выбора: высота кнопки и поле вокруг ряда.
    static let pillHeight: CGFloat = 34
    static let pillPadding: CGFloat = 4

    /// Клетка с фигуркой узора в настройках. Столько же, сколько у
    /// кнопки в панели: четыре такие клетки с промежутками умещаются в
    /// строку даже на узком телефоне.
    static let pieceTile: CGFloat = 44

    /// Насколько глушится фигурка, которой в узоре сейчас нет.
    /// Не до нуля: выбор должен показывать и то, что можно включить.
    static let pieceOff = 0.22

    /// Кнопка настроек: коробка значка и сам значок.
    ///
    /// Коробка задаёт размер кнопки — системная кнопка меряет себя по
    /// содержимому, — а шестерёнка нарисована крупнее коробки и просто
    /// выходит за неё. Так знак стал заметнее, а кнопка осталась той же:
    /// подними кегль обычным порядком, вместе с ним выросла бы и она.
    static let gearBox: CGFloat = 24
    static let gearGlyph: CGFloat = 24

    /// Кружок оттенка в ряду выбора цвета. Меньше клетки с фигуркой:
    /// цветов шесть, а фигурок четыре, и в ту же строку они иначе не
    /// встанут.
    static let swatch: CGFloat = 28

    /// Размытие свечения вокруг фигурок на гребне волны.
    static let splashGlow: CGFloat = 8

    /// Какую долю смены набора занимает проход одной фигурки: она
    /// сжимается до нуля и тут же вырастает обратно. Остаток — время, за
    /// которое очередь обходит экран.
    ///
    /// Доля большая, и это главное здесь число. Мелкая означала бы, что
    /// вся сетка успевает исчезнуть прежде, чем начнёт появляться, — то
    /// есть пустой экран посреди смены. При этой фигурки уходят и
    /// приходят внахлёст: впереди ещё стоит прежний узор, позади уже
    /// стоит новый, а пусто только в узкой полосе между ними.
