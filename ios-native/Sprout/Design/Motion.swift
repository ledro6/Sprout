import SwiftUI

/// Движение интерфейса — в одном месте, чтобы подкручивать его целиком,
/// а не по файлам.
///
/// Везде пружины, а не кривые. Пружину можно прервать на середине: она
/// продолжит с той скорости, что набрала, тогда как кривая прыгнет к
/// новому значению.
///
/// Числа — те, что были на телефоне и читались. Попытка сделать движение
/// «плавнее» их пригладила: отскок вдвое меньше, путь короче, время
/// длиннее, — и волна перестала быть заметной вовсе. Плавность здесь не
/// в осторожности размаха, а в том, что пружина одна и её никто не
/// прерывает.
enum Motion {
    /// Появление карточки в сетке.
    static let appear = Animation.spring(duration: 0.45, bounce: 0.28)

    /// Насколько позже стартует соседняя карточка. Волна должна успеть
    /// прочитаться, но не превращаться в очередь: восемь карточек с этим
    /// шагом укладываются в полсекунды.
    static let stagger = 0.055

    /// Уход карточек при смене комнаты. Короче появления: уходящее
    /// внимания не просит.
    static let leave = Animation.easeOut(duration: 0.24)

    /// Возвращение ореолов, когда экран растения закрылся.
    ///
    /// Секунду тени нет вовсе — карточка успевает сложиться обратно и
    /// встать на место, — и только потом она набирает яркость. В обратную
    /// сторону анимации нет: при открытии ореол должен исчезнуть сразу,
    /// до первого кадра разворачивания.
    static let halo = Animation.easeOut(duration: 0.5).delay(1)

    /// Смена числа: старое размывается и уступает место новому. Тот же
    /// переход, которым система меняет цифры у себя.
    static let number = Animation.easeInOut(duration: 0.3)

    /// Пульс свечения у совсем сухого растения: полный вдох-выдох за две
    /// с половиной секунды. Медленно — чтобы читалось дыханием, а не
    /// миганием, и всё же не давало пройти мимо.
    static let pulsePeriod = 1.25

    /// До какой доли яркости свечение опадает на вдохе.
    static let pulseLow = 0.45

    /// Сколько идёт волна всплесков по узору, когда растение полили.
    ///
    /// Она же теперь единственное, чем полив отмечен: блик, проходивший
    /// по плашке под растением, убран, а вместо него фигурки на гребне
    /// волны синеют и вместе с размером возвращаются к своему цвету.
    ///
    /// Столько же, сколько было у волны с самого начала.
    ///
    /// Её пробовали ускорить до полутора секунд заодно с переходами — и
    /// зря: у волны своя работа. Переход показывает выбор, и ему надо
    /// успеть до следующего нажатия; волна же отмечает полив, нажатие у
    /// неё одно, и торопиться ей некуда. Экран она проходит быстрее, чем
    /// идёт сама: до дальнего угла добирается примерно за полторы
    /// секунды, остальное — хвост, который уже за краем.
    static let cheerSeconds = 2.4

    /// Прыжок элемента на гребне волны полива: вверх и обратно.
    ///
    /// Вместе — 0.66 с, и это не круглое число, а подгонка: ровно столько
    /// длится всплеск одной фигурки узора, `popSpan` от всей волны. Вниз
    /// дольше, чем вверх: гребень подхватывает резко, а опускается всё
    /// плавно.
    ///
    /// Пружинами, а не расписанием кадров. Узору расписание нужно — у
    /// него три сотни фигурок, и у каждой свой размер в каждом кадре.
    /// Элементу нужны всего два движения, и пружины отыграют их сами, не
    /// пересобирая тело на каждый кадр.
    static let rideUpSeconds = 0.16
    static let rideUp = Animation.spring(duration: rideUpSeconds, bounce: 0.3)
    static let rideDown = Animation.spring(duration: 0.26, bounce: 0.2)

    /// Прыжок идёт ровно тогда, когда до элемента доходит гребень.
    ///
    /// Своего сжатия у очереди больше нет. Оно здесь было: элементы
    /// подпрыгивали втрое раньше волны, чтобы прыжок читался откликом на
    /// нажатие. Но откликом он и так читается — у политого растения
    /// гребень под плашкой с самого начала, — а у дальних выходило, что
    /// они прыгают в пустоту, задолго до того, как под ними что-то
    /// происходит. Черёд у прыжка тот же, что у фигурки узора под ним, и
    /// это его единственный смысл: видно, как волна идёт по экрану, по
    /// тому, что она поднимает.

    /// Разброс периода между растениями, доля от него же.
    ///
    /// Одного сдвига фазы мало: при одинаковом периоде карточки идут
    /// параллельно и разница читается как небрежность, а не как
    /// несколько растений. С разным периодом они расходятся и сходятся
    /// сами, и такт не собирается никогда.
    static let pulseSpread = 0.5

    /// Появление верхней панели на экране растения: она проступает из
    /// размытия.
    static let chrome = Animation.easeOut(duration: 0.5)

    /// Насколько она отстаёт от разворачивания карточки.
    ///
    /// Отставание нарочное: карточка разворачивается в экран — это
    /// главное движение, и панель, вспыхнувшая одновременно с ним, спорит
    /// с ним за внимание. Дав ей отстать на треть разворота, получаем то
    /// же, что в Музыке при открытии альбома: сначала обложка встаёт на
    /// место, следом из размытия проступает верх.
    ///
    /// Отдельным числом, а не через `delay` у самой анимации. Анимация
    /// выбирается тем же флагом, что и размытие, и с задержкой внутри
    /// уход рисковал уйти с той же задержкой — то есть уже после того,
    /// как экран сложился.
    static let chromeDelay = 0.18

    /// Уход панели, когда экран закрывают.
    ///
    /// Кривая с быстрым началом, а не с плавным. У ухода на всё про всё
    /// пятая доля секунды, и вялое начало съедало бы её целиком: на этом
    /// уход и не был виден — за `easeIn` элементы к моменту закрытия
    /// гасли меньше чем наполовину, а остаток доигрывала уже сама панель,
    /// разом.
    static let chromeOutSeconds = 0.2
    static let chromeOut = Animation.easeOut(duration: chromeOutSeconds)

    /// Насколько закрытие экрана ждёт этот уход.
    ///
    /// Ждать приходится: панель на экране растения рисует UIKit, и на
    /// время складывания он снимает с неё кадр. Начни складывание сразу —
    /// в кадр попала бы панель как есть, целая и резкая.
    ///
    /// Ждём почти весь уход: за `easeOut` к этому мгновению от элементов
    /// не остаётся ничего, а двух сотых секунды рука не различает.
    static let chromeLead = chromeOutSeconds - 0.02

    /// Заставка при запуске: элементы всплывают поочерёдно, с этим шагом,
    /// и держатся, пока приложение поднимается.
    ///
    /// Держится она недолго. Заставка нужна затем, чтобы на холодном
    /// запуске не было чёрного экрана, а не затем, чтобы её разглядывали.
    static let welcomeIn = Animation.spring(duration: 0.55, bounce: 0.18)
    static let welcomeStep = 0.22
    static let welcomeHold = 1.6
    static let welcomeLeaveSeconds = 0.45
    static let welcomeLeave = Animation.easeOut(duration: welcomeLeaveSeconds)

    /// Насколько мелким приходит элемент заставки.
    static let welcomeScale: CGFloat = 0.86

    /// Логотип собирается по частям: лист со стеблем, следующий лист,
    /// верхний листок, капля, вторая капля — снизу вверх, как растёт
    /// росток.
    ///
    /// Ход у частей общий и ровный, а расходятся они задержкой: у каждой
    /// свой отрезок внутри этого хода, сдвинутый на `logoLag`. Своей
    /// анимации у части быть не может — рисует их всех один холст, и
    /// снаружи у него одно-единственное число.
    static let logoSeconds = 0.85
    static let logoLag = 0.13

    /// Насколько мелкой приходит часть логотипа. Мельче, чем текст: у
    /// части своя середина, и рост от неё виден лучше, чем у строки.
    static let logoScale: CGFloat = 0.7

    /// Вход самого приложения, ступень за ступенью: узор, заголовок,
    /// комната, сетка, панель вкладок. Шаг мельче, чем у заставки: это
    /// уже не представление, а сборка экрана.
    static let enter = Animation.spring(duration: 0.5, bounce: 0.2)
    static let enterStep = 0.13

    /// Откуда ступень приходит: чуть снизу.
    static let enterRise: CGFloat = 22

    /// Всходы узора: за сколько он весь проступает при запуске.
    ///
    /// Не «появляется», а всходит: каждая фигурка вырастает сама, своим
    /// чередом, очередь идёт снизу вверх. Одной прозрачностью на весь
    /// слой этого было не показать — узор восьмипроцентной плотности, и
    /// полсекунды еле видной ряби глаз не ловит.
    static let bloomSeconds = 1.1

    /// Промежуток между переходами узора, идущими друг за другом.
    ///
    /// Нажали второй раз, пока первый переход не отыграл, — второй его не
    /// обрывает, а встаёт следом. Обрыв виден сразу: половина экрана
    /// осталась бы в старом наборе и прыгнула бы в новый кадром.
    ///
    /// Промежуток маленький нарочно: он нужен, только чтобы два перехода
    /// не слились в один и было видно, что их два. Ноль слил бы их,
    /// заметная пауза читалась бы заминкой.
    static let changeGap = 0.08

    /// Сколько переходов может ждать своей очереди.
    ///
    /// Раньше ждал ровно один: третье нажатие подряд сливалось со вторым.
    /// Это было бережно к глазу, но врало пальцу — нажал пять раз, увидел
    /// два перехода. Теперь ждут все, но не больше этого: очередь —
    /// отклик на нажатия, а не их архив, и десять тычков не должны
    /// оборачиваться полуминутой узора. Переполнилась — последний ждущий
    /// перенимает цель нового: хвост не растёт, а конец пути остаётся
    /// верным.
    static let queued = 3

    /// Смена цвета узора и смена набора фигурок — та же волна, что у
    /// полива, только быстрее.
    ///
    /// Раньше у каждой был не только свой срок — 0.8 с у перекраски, 1.3 у
    /// смены набора, 2.4 у волны, — но и своя мерка расстояния. Из-за
    /// этого одно и то же движение, круг из-под пальца, на каждом переходе
    /// ползло по экрану со своей скоростью, и три перехода читались тремя
    /// разными анимациями. Мерка (`Front.reach`) и доля на одну фигурку
    /// (`Metrics.popSpan`) теперь общие: движение одно.
    ///
    /// А срок у переходов свой и короче. Они показывают выбор и встают в
    /// очередь: три нажатия подряд по две с половиной секунды — это семь
    /// секунд узора, за которые о нажатиях успеваешь забыть. У волны
    /// нажатие одно, и спешить ей некуда.
    static let repaintSeconds = 1.5
    static let swapSeconds = 1.5

    /// Переезд стеклянной капсулы в ряду выбора — темы, порога.
    ///
    /// Пружина, и короткая: капсула проходит треть ширины экрана, и
    /// кривая той же длины читалась бы вялой. Отскок мелкий — она не
    /// предмет, который бросили, а отметка, которая переехала.
    static let pill = Animation.spring(duration: 0.32, bounce: 0.16)

    /// Откуда карточка приходит: ниже своего места и мельче. Размах
    /// виден — иначе появления попросту не заметно.
    static let rise: CGFloat = 26
    static let scale: CGFloat = 0.9
}
