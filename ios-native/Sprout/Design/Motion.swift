import SwiftUI

/// Движение интерфейса — в одном месте, чтобы подкручивать его целиком,
/// а не по файлам.
///
/// Везде пружины, а не кривые. Пружину можно прервать на середине: она
/// продолжит с той скорости, что набрала, тогда как кривая прыгнет к
/// новому значению. Отскок держим маленьким — это подача содержимого, а
/// не пружинка на двери; при большом отскоке движение читается
/// игрушечным и на глаз кажется дёрганым, даже когда идёт ровно.
enum Motion {
    /// Появление карточки в сетке.
    static let appear = Animation.spring(duration: 0.55, bounce: 0.16)

    /// Насколько позже стартует соседняя карточка. Волна должна успеть
    /// прочитаться, но не превращаться в очередь: восемь карточек с этим
    /// шагом укладываются в треть секунды.
    static let stagger = 0.045

    /// Уход карточек при смене комнаты. Короче появления: уходящее
    /// внимания не просит.
    static let leave = Animation.easeOut(duration: 0.24)

    /// Откуда карточка приходит: чуть ниже своего места и чуть мельче.
    /// Небольшой размах — половина плавности: чем короче путь, тем
    /// меньше заметны неровности кадров.
    static let rise: CGFloat = 20
    static let scale: CGFloat = 0.94
}
