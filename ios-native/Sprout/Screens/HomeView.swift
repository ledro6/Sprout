import SwiftUI
import UniformTypeIdentifiers

/// Главная: заголовок раздела, выбор комнаты и растения — плиткой или
/// списком.
struct HomeView: View {
    @Environment(Garden.self) private var garden

    /// Глубина выреза: на столько растяжка под строкой комнаты уходит
    /// вверх сверх заголовка, чтобы дотянуться до самого края экрана.
    @Environment(\.notch) private var notch

    @State private var roomIndex = 0

    /// Карточки, которые в этой комнате уже всплыли. Журнал лежит здесь,
    /// а не в самой карточке: сетка ленивая, уехавшие за край карточки
    /// она выбрасывает вместе с их памятью, а сетка остаётся.
    ///
    /// Именно состояние, а не ссылочный тип рядом с ним. Здесь была
    /// оптимизация: журнал переехал в класс, за которым SwiftUI не
    /// следит, чтобы отметка «всплыла» не перерисовывала экран восемь раз
    /// за волну. Она и не перерисовывала — и в этом была поломка. Флаг
    /// «эту уже показывали» считается ниже, в теле экрана; не
    /// пересобравшись, тело так и отдавало сетке «нет, не показывали» —
    /// для каждой карточки и навсегда. Сетка ленивая, уехавшую за край
    /// карточку она создаёт заново, брала этот застывший ответ и играла
    /// появление снова.
    ///
    /// Восемь пересборок тела за полсекунды — цена правильного ответа, и
    /// она невелика: фон при них не перерисовывается, его вью не
    /// меняется.
    @State private var revealed: Set<String> = []

    /// Пространство для перехода на растение: карточка не исчезает, а
    /// разворачивается в экран.
    @Namespace private var cardZoom

    /// Что сейчас открыто поверх главной. Путь держим сами: переход надо
    /// начинать не раньше, чем погашены ореолы, а стек об ореолах не
    /// знает.
    @State private var path: [Plant.ID] = []

    /// Чья карточка сейчас разворачивается в экран.
    ///
    /// Номер, а не «да/нет» на всю сетку: гаснуть должны ореолы только у
    /// той карточки, что открывается, — остальные к переходу отношения не
    /// имеют и мигать им незачем.
    ///
    /// И отдельным состоянием, а не «путь пуст»: по пустоте пути ореол
    /// гас бы одновременно с началом перехода, а этого мало. Кадр
    /// разворачивания снимается с карточки в том же проходе, и ореол
    /// попадал в снимок — на экране он уезжал за карточкой прямоугольным
    /// хвостом. Гасить надо проходом раньше.
    @State private var opening: Plant.ID?

    /// Открыты ли настройки. Отдельным листом, а не вкладкой: настройки
    /// — не место, где живут, а место, куда заходят и возвращаются.
    @State private var settings = false

    /// Открыта ли правка комнат — тоже листом, по той же причине.
    @State private var roomsOpen = false

    /// Правят ли сейчас порядок растений.
    ///
    /// Режимом, а не всегда: долгое нажатие на карточку уже занято её
    /// меню — полить, переименовать, удалить, — и перетаскивание с ним
    /// спорило бы за одно и то же удержание. Как на экране «Домой»:
    /// сперва «Изменить», потом двигать.
    @State private var editing = false

    /// Кого сейчас тащат. Один на всю полку: бледнеть должна только его
    /// карточка, а знать, над кем его держат, должна каждая.
    @State private var dragged: Plant.ID?

    /// Насколько экран прокручен от верха.
    @State private var scrolled: CGFloat = 0

    /// Высота заголовка раздела — путь, который он проходит, прежде чем
    /// уйти под вырез. Не задана числом: заголовок крупный и растёт
    /// вместе с настройкой размера текста.
    @State private var titleHeight: CGFloat = 1

    /// Размеры кнопки комнаты: в покое и доросшей до заголовка. Оба идут
    /// за настройкой размера текста, каждый — за своим стилем, поэтому и
    /// растут по-разному.
    @ScaledMetric(relativeTo: .headline)
    private var roomSize = Typography.roomSize
    @ScaledMetric(relativeTo: .largeTitle)
    private var roomGrown = Typography.roomGrown

    /// Доля пути, пройденного заголовком: 0 — экран в покое, 1 — заголовок
    /// ушёл целиком и строка комнаты встала на его место.
    private var grown: CGFloat {
        min(max(scrolled / titleHeight, 0), 1)
    }

    /// Как лежат растения — плиткой или списком. См. `Settings.Look`.
    private var look: Settings.Look { Settings.shared.look }

    /// Открытая комната. Номер придерживаем в границах: комнат может
    /// стать меньше, а выбор остаться прежним.
    ///
    /// Комнат может не быть вовсе — сад стёрли в профиле или удалили
    /// последнюю комнату. Тогда и открывать нечего: прежде здесь было
    /// обращение к первой комнате пустого списка, и главная падала.
    private var room: Room? {
        guard !garden.rooms.isEmpty else { return nil }
        return garden.rooms[min(roomIndex, garden.rooms.count - 1)]
    }

    /// Растения открытой комнаты — в выбранном порядке.
    private var plants: [Plant] {
        Settings.shared.order.arrange(room?.plants ?? [])
    }

    var body: some View {
        NavigationStack(path: $path) {
            ScrollView {
                // Заголовок уезжает с содержимым, строка комнаты
                // прилипает к верху, дойдя до него, — как список в
                // Музыке. Даёт это закреплённая шапка секции: своей
                // возни с наложением слоёв здесь не нужно.
                LazyVStack(alignment: .leading, spacing: 0,
                           pinnedViews: [.sectionHeaders]) {
                    // Ступени входа: заголовок, комната, сетка. Узор
                    // приходит первым, из самого фона, панель вкладок
                    // последней — см. `Launch`.
                    SectionTitle("Главная")
                        .modifier(Enter(step: 2))
                        .onGeometryChange(for: CGFloat.self) { $0.size.height }
                            action: { titleHeight = max($0, 1) }
                    Section {
                        // Сетки до её ступени нет вовсе, а не спрятана.
                        // У карточек своя волна появления, и она играет,
                        // когда карточки создаются: спрячь их — волна
                        // отыграла бы под заставкой, и на экран они
                        // выехали бы разом.
                        if Launch.shared.step >= 4 {
                            shelf
                        }
                    } header: {
                        roomBar
                            .modifier(Enter(step: 3))
                    }
                }
            }
            // Сколько уехало содержимое. Вставка сверху прибавлена,
            // чтобы в покое выходил ноль: у прокрутки под безопасной
            // зоной смещение стартует отрицательным.
            .onScrollGeometryChange(for: CGFloat.self) {
                $0.contentOffset.y + $0.contentInsets.top
            } action: { _, offset in
                scrolled = offset
            }
            // Отпустить карточку можно где угодно на экране, а не только
            // над другой карточкой, — см. `Rest`.
            .onDrop(of: [.text], delegate: Rest(dragged: $dragged, drop: land))
            .background { SproutBackground() }
            // Панель сверху не нужна: заголовок раздела живёт в самом
            // содержимом. У экрана растения панель своя.
            .toolbar(.hidden, for: .navigationBar)
            // А нижняя — последняя ступень входа: выезжает снизу, когда
            // экран уже собран. Прячем её здесь, а не в корне: видимость
            // панели вкладок задаётся содержимым вкладки.
            .toolbar(Launch.shared.step >= Launch.last ? .visible : .hidden,
                     for: .tabBar)
            // По номеру, а не копией растения: его поливают и
            // переименовывают, и экран должен показывать живое состояние,
            // а не слепок, снятый при переходе.
            .navigationDestination(for: Plant.ID.self) { id in
                PlantView(plantID: id)
                    .navigationTransition(.zoom(sourceID: id, in: cardZoom))
            }
        }
        // Вернулись на главную — ореолы проявляются. Полсекунды их нет
        // вовсе: карточка за это время складывается обратно и встаёт на
        // место, и тень проступает уже под стоящей.
        .onChange(of: path) { _, now in
            if now.isEmpty {
                withAnimation(Motion.halo) { opening = nil }
            }
        }
        // Сменили комнату — растения другие, и всплыть должны все.
        .onChange(of: roomIndex) { _, _ in revealed.removeAll() }
        // Комнаты переставили, переименовали или удалили — выбор остаётся
        // на той же комнате, а не на том же номере.
        .onChange(of: garden.rooms.map(\.name)) { old, new in
            follow(from: old, to: new)
        }
        // Растение ушло из комнаты — удалили или перевезли. Из журнала
        // показанных оно уходит тоже: вернут его — и оно всплывёт на своё
        // место так же, как всплывало при открытии комнаты, а не
        // появится щелчком.
        .onChange(of: room?.plants.map(\.id) ?? []) { old, new in
            revealed.subtract(Set(old).subtracting(new))
        }
        .sheet(isPresented: $settings) { SettingsView() }
        // Сад передаём листу явно. Лист и так наследует окружение того,
        // кто его показал, но без сада правка комнат не откроется вовсе —
        // падением, — и полагаться тут на наследование незачем.
        .sheet(isPresented: $roomsOpen) { RoomsView().environment(garden) }
    }

    /// Удержать выбор на той же комнате, что бы ни случилось со списком.
    ///
    /// Нашлась по имени — встаём на её новый номер. Не нашлась, а комнат
    /// столько же — её переименовали, номер прежний. Комнат стало меньше —
    /// выбранную удалили, и встаём на соседнюю.
    private func follow(from old: [String], to new: [String]) {
        guard old.indices.contains(roomIndex) else {
            roomIndex = min(roomIndex, max(new.count - 1, 0))
            return
        }
        if let index = new.firstIndex(of: old[roomIndex]) {
            roomIndex = index
        } else if old.count != new.count {
            roomIndex = min(roomIndex, max(new.count - 1, 0))
        }
    }

    /// Открыть растение.
    ///
    /// Гашение и переход — разными проходами, и это здесь главное. В
    /// одном проходе SwiftUI успевает снять кадр разворачивания вместе с
    /// ещё горящим ореолом, и тот уезжает за карточкой прямоугольным
    /// хвостом. Отложенный на проход переход стоит один кадр — его не
    /// видно, а хвоста больше нет.
    private func show(_ id: Plant.ID) {
        opening = id
        Task { @MainActor in path.append(id) }
    }

    /// Строка комнаты. Пока заголовок уезжает, подпись комнаты растёт
    /// ему навстречу и к концу пути становится ровно его размера: место
    /// заголовка занимает не пустота, а название комнаты.
    private var roomBar: some View {
        HStack(alignment: .center, spacing: 12) {
            if garden.rooms.isEmpty {
                // Выбирать не из чего, но место под строкой должно
                // остаться: на нём держатся кнопки справа.
                Color.clear
                    .frame(maxWidth: .infinity, minHeight: 44)
            } else {
                RoomPicker(rooms: garden.rooms.map(\.name),
                           selection: $roomIndex,
                           size: roomSize + (roomGrown - roomSize) * grown,
                           onEdit: { roomsOpen = true })
                    .frame(maxWidth: .infinity, alignment: .leading)
                    .sproutRide()
            }
            corner
        }
        .padding(.horizontal, Metrics.contentMargin)
        .background(alignment: .top) { headerWash }
    }

    /// Кнопки справа сверху: вид, правка порядка и настройки — в одном
    /// ряду с комнатой.
    ///
    /// Здесь, а не в панели навигации: панели на главной нет вовсе —
    /// заголовок раздела живёт в самом содержимом, — а строка комнаты
    /// закреплена и не уезжает при прокрутке. То есть кнопка стоит в
    /// единственном месте главной, которое всегда наверху.
    ///
    /// Стекло не своё, а системное: `.glass` с круглой каймой. Своё здесь
    /// было и убрано. Стеклянный материал оно давало, а поведение — нет:
    /// стекло висело на значке внутри кнопки, а нажатие обрабатывала сама
    /// кнопка обычным стилем, то есть приглушением. Выходила стеклянная
    /// картинка, которая под пальцем просто тускнеет. Системный стиль
    /// рисует ту же кнопку, что и сама iOS, и с ней приходит всё
    /// остальное: продавливание под пальцем, отскок пружиной, блик,
    /// который идёт за точкой касания, и подмена материала, когда в
    /// настройках включают «Уменьшение прозрачности». Ничего из этого
    /// руками не повторяется.
    ///
    /// Размер кнопки задаёт коробка значка: системная кнопка меряет себя
    /// по содержимому и своим полям, как соседние кнопки в панелях iOS.
    /// Сама шестерёнка нарисована крупнее коробки и выходит за неё — так
    /// знак стал заметнее, а кнопка осталась прежней. Подними кегль
    /// обычным порядком, вместе с ним выросла бы и она.
    ///
    /// Поднята кнопка на строку заголовка, и поднята хитро: она живёт в
    /// закреплённой строке комнаты, а смещается вверх ровно на высоту
    /// заголовка — и тем меньше, чем дальше уехал экран. В покое это
    /// ставит её вровень с «Главной», а по мере прокрутки смещение тает
    /// одновременно с тем, как строка комнаты подходит к верху. В сумме
    /// кнопка не двигается вовсе: стоит на одном месте экрана и в покое,
    /// и на прокрутке. Оставь её в своей строке — уехала бы вниз; положи
    /// в строку заголовка — уехала бы с ним за край.
    ///
    /// Вид и правка встали рядом с шестерёнкой и едут вместе с ней: это
    /// те же кнопки «для всего экрана», и место у них то же — единственное
    /// на главной, которое всегда наверху.
    private var corner: some View {
        HStack(spacing: Metrics.cornerGap) {
            viewMenu
            editButton
            SproutGear { settings = true }
        }
        .sproutRide()
        .offset(y: -titleHeight * (1 - grown))
    }

    /// Вид и порядок — одним меню, как в «Файлах»: сверху «плиткой или
    /// списком», под ними — в каком порядке.
    ///
    /// Значок на кнопке — того вида, что сейчас на экране. Кнопка не
    /// переключает, а открывает меню, и значок говорит, что в нём сейчас
    /// выбрано.
    ///
    /// Смена вида заново проигрывает волну появления: карточки не
    /// перетекают в строки, а уходят и приходят, и волна показывает, что
    /// это те же растения, просто разложенные иначе. Смена порядка —
    /// наоборот, перекладка тех же карточек пружиной: растения остались,
    /// поменялись только места.
    private var viewMenu: some View {
        Menu {
            Section("Вид") {
                Picker("Вид", selection: Binding(
                    get: { look },
                    set: { chosen in
                        withAnimation(Motion.arrange) {
                            revealed.removeAll()
                            Settings.shared.look = chosen
                        }
                    }
                )) {
                    ForEach(Settings.Look.allCases) { item in
                        Label(item.title, systemImage: item.icon).tag(item)
                    }
                }
            }
            Section("Порядок") {
                Picker("Порядок", selection: Binding(
                    get: { Settings.shared.order },
                    set: { sort($0) }
                )) {
                    ForEach(Settings.Order.allCases) { item in
                        Label(item.title, systemImage: item.icon).tag(item)
                    }
                }
            }
        } label: {
            Image(systemName: look.icon)
                .font(.system(size: Metrics.cornerGlyph, weight: .semibold))
                .foregroundStyle(Palette.ink)
                .frame(width: Metrics.gearBox, height: Metrics.gearBox)
                .contentTransition(.symbolEffect(.replace))
        }
        .menuStyle(.button)
        .buttonStyle(.glass)
        .buttonBorderShape(.circle)
        .accessibilityLabel("Вид и порядок")
    }

    /// Выбрать порядок.
    ///
    /// Не ручной порядок заканчивает правку: тащить карточку по сетке,
    /// которую тут же пересортируют, бессмысленно — она встала бы не
    /// туда, куда её опустили.
    private func sort(_ order: Settings.Order) {
        withAnimation(Motion.arrange) {
            Settings.shared.order = order
            if order != .manual {
                editing = false
                dragged = nil
            }
        }
    }

    /// «Изменить» — и «Готово», пока правят.
    ///
    /// «Готово» выделено — синим стеклом, как у системных кнопок,
    /// которыми заканчивают правку: пока оно горит, экран не в покое, и
    /// это должно быть видно с первого взгляда.
    ///
    /// Высота подписи — та же коробка, что у значков: без неё текстовая
    /// кнопка выходила бы на пару пунктов ниже соседних круглых.
    @ViewBuilder
    private var editButton: some View {
        if editing {
            Button {
                withAnimation(Motion.arrange) {
                    editing = false
                    dragged = nil
                }
            } label: {
                Text("Готово")
                    .fontWeight(.semibold)
                    .frame(height: Metrics.gearBox)
            }
            .buttonStyle(.glassProminent)
        } else {
            Button {
                // Расставлять руками — значит выбрать ручной порядок. Если
                // растения лежали по имени или по сроку, сетка
                // перекладывается в ручной порядок прямо сейчас, и тащат
                // уже по нему.
                withAnimation(Motion.arrange) {
                    editing = true
                    Settings.shared.order = .manual
                }
            } label: {
                Text("Изменить")
                    .frame(height: Metrics.gearBox)
            }
            .buttonStyle(.glass)
        }
    }

    /// Растяжка под строкой комнаты: от самого верха экрана до конца
    /// строки, дальше сход. Гасит карточки, которые заезжают под строку
    /// снизу и уходят под строку состояния.
    ///
    /// Верхнего края у неё нет. Он есть в разметке, но уведён выше края
    /// экрана и обрезан прокруткой — а видимого края и не должно быть:
    /// начинаясь у строки комнаты, растяжка шла поперёк экрана заметной
    /// чертой, и никакой сход эту черту не убирал. Подложки под вырезом
    /// на главной поэтому больше нет: два слоя, гасящий и показывающий
    /// узор во всю силу, дали бы ровно такую же черту на своей границе.
    ///
    /// Подъём — глубина выреза плюс высота заголовка: столько от верха
    /// строки до края экрана, пока строка ещё не прилипла. Прилипнув,
    /// она подойдёт ближе, и лишнее просто уйдёт за край.
    ///
    /// Сход прицеплен к низу строки, а не задан абсолютной высотой, — так
    /// он не поедет, если подпись комнаты займёт другую высоту.
    private var headerWash: some View {
        VStack(spacing: 0) {
            Palette.background.opacity(Metrics.headerWashOpacity)
            LinearGradient(
                colors: [
                    Palette.background.opacity(Metrics.headerWashOpacity),
                    Palette.background.opacity(0),
                ],
                startPoint: .top,
                endPoint: .bottom
            )
            .frame(height: Metrics.headerWashFade)
        }
        .padding(.top, -(notch + titleHeight))
        .padding(.bottom, -Metrics.headerWashDrop)
        // Проступает по мере прокрутки. В покое гасить нечего — карточек
        // под строкой ещё нет, — а сплошная растяжка от края экрана
        // накрыла бы заголовок, и «Главная» читалась бы серой. К тому
        // времени, как она наберёт полную силу, заголовок уже уходит под
        // неё сам.
        .opacity(Double(grown))
        .allowsHitTesting(false)
    }

    /// Растения комнаты — плиткой или списком. См. `Shelf`.
    ///
    /// Общего стеклянного контейнера нет, и это не забыто. Контейнер
    /// сводил стекло всех карточек в один проход рисования — экономия
    /// настоящая, но платить за неё пришлось тем, ради чего экран и
    /// делался. Он собирает содержимое в один слой, и обе анимации
    /// карточки шли через него: разворачивание в экран теряло источник, а
    /// волна появления играла не по карточкам, а по всей сетке разом.
    /// Карточки к тому же намеренно не сливаются краями — то есть от
    /// контейнера здесь и не нужно ничего, кроме прохода.
    @ViewBuilder
    private var shelf: some View {
        if plants.isEmpty {
            empty
        } else {
            Shelf(look) {
                ForEach(Array(plants.enumerated()), id: \.element.id) { item in
                    PlantTile(plant: item.element,
                              look: look,
                              opening: opening,
                              zoom: cardZoom,
                              open: show,
                              index: item.offset,
                              room: roomIndex,
                              appears: !revealed.contains(item.element.id),
                              onShown: { revealed.insert(item.element.id) },
                              editing: editing,
                              dragged: $dragged,
                              move: shift,
                              drop: land)
                        // Явная личность у каждой карточки: без неё ленивая
                        // сетка подсовывала контекстному меню чужой узел — см.
                        // `PlantTile`.
                        .id(item.element.id)
                }
            }
            // Ровно на свес растяжки: в покое сход до карточек не
            // дотягивается, а уезжающим наверх есть где раствориться.
            .padding(.top, Metrics.headerWashDrop)
            .padding(.horizontal, Metrics.contentMargin)
            .padding(.bottom, 24)
            // Затухание уходящим карточкам. Без этого их нечем анимировать:
            // переход у них описан, но анимации в области видимости нет, и
            // старая комната просто пропадала кадром.
            .animation(Motion.leave, value: roomIndex)
        }
    }

    /// Пустая комната — или пустой сад.
    ///
    /// Не пустое место, а строка о том, что делать: пустой экран без
    /// единого слова читается поломкой, а не пустой комнатой. Приходит тем
    /// же системным размытием, что и весь текст приложения.
    private var empty: some View {
        // Строкой заранее: собранная прямо в `Text` из тернарного и
        // сложений, она заставляла бы компилятор перебирать все
        // перегрузки `Text` для каждого куска.
        let note: String = garden.rooms.isEmpty
            ? "В саду пока ничего не растёт. Посадите первое растение во вкладке «Добавить»."
            : "В этой комнате пока ничего не растёт. Посадите сюда растение во вкладке «Добавить» или перевезите из другой комнаты."
        return VStack(spacing: 14) {
            Image(systemName: "leaf")
                .font(.system(size: 30, weight: .regular))
                .foregroundStyle(.tertiary)
            Text(note)
                .font(Typography.settingNote)
                .foregroundStyle(.secondary)
                .multilineTextAlignment(.center)
                .fixedSize(horizontal: false, vertical: true)
            if garden.rooms.isEmpty {
                Button("Завести комнату") { roomsOpen = true }
                    .buttonStyle(.glass)
                    .font(Typography.settingNote)
            }
        }
        .frame(maxWidth: .infinity)
        .padding(.horizontal, 48)
        .padding(.top, 120)
        .transition(.blurReplace)
    }

    /// Перетаскиваемое растение зашло на чужое место — соседи
    /// расступаются.
    private func shift(_ who: Plant.ID, _ spot: Plant.ID) {
        withAnimation(Motion.arrange) { garden.move(who, to: spot) }
    }

    /// Карточку отпустили: она уже на своём новом месте, осталось вернуть
    /// ей цвет.
    private func land() {
        withAnimation(Motion.arrange) { dragged = nil }
    }
}
