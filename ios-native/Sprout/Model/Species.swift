import Foundation

/// Что увидела на снимке система: ярлык и насколько она в нём уверена.
///
/// Свой тип, а не наблюдение Vision. Здесь одни строки и числа, и их можно
/// прогнать где угодно, где есть Swift; Vision же есть только на
/// платформах Apple, да и в симуляторе его классификатор не работает.
/// Разбор ярлыков — самое хрупкое место во всей затее, и проверять его
/// надо, не запуская телефон.
struct Sighting: Hashable, Sendable {
    var name: String
    var confidence: Double
}

/// Догадка о растении: вид, как его зовут по-русски, и за сколько суток
/// оно высыхает.
struct Guess: Hashable, Sendable {
    var species: String
    var dryingDays: Double
    var confidence: Double
}

/// Перевод с языка классификатора на язык сада.
///
/// Классификатор Apple отвечает английскими ярлыками из своего словаря —
/// «cactus», «flowering_plant», «houseplant». Ярлыков в нём тысячи, и
/// угадывать точный вид по ним нечестно: он различает кактус и папоротник,
/// но не отличит замиокулькас от сансевиерии. Поэтому здесь не
/// определитель, а подсказка: она заполняет поле «вид» и срок полива, а
/// последнее слово остаётся за хозяином — оба поля правятся руками.
enum Species {
    /// Слова, по которым узнаётся растение, и что они значат.
    ///
    /// Порядок — от частного к общему, и это главное здесь. Ярлыки
    /// приходят пачкой: на снимке кактуса классификатор назовёт и
    /// «cactus», и «succulent», и «plant», и «houseplant». Идти надо по
    /// этому списку, а не по уверенности: самый уверенный ярлык почти
    /// всегда самый общий — «растение». Кактус в ответе полезнее.
    ///
    /// Сроки сушки — те же, что у растений в макетном саду: кактус месяц,
    /// папоротник неделю, зелень несколько дней. Их всё равно правят
    /// руками, но начинать с семи суток для кактуса было бы вредным
    /// советом.
    static let table: [(word: String, species: String, days: Double)] = [
        ("cactus", "Кактус", 30),
        ("succulent", "Суккулент", 21),
        ("aloe", "Алоэ", 14),
        ("jade", "Толстянка", 12),
        ("bonsai", "Бонсай", 4),
        ("orchid", "Орхидея", 9),
        ("fern", "Папоротник", 5),
        ("palm", "Пальма", 11),
        ("bamboo", "Бамбук", 6),
        ("ivy", "Плющ", 8),
        ("monstera", "Монстера", 9),
        ("philodendron", "Филодендрон", 8),
        ("ficus", "Фикус", 7),
        ("dracaena", "Драцена", 8),
        ("violet", "Фиалка", 4.5),
        ("tulip", "Тюльпан", 9),
        // Розмарин раньше розы, и это не прихоть: «rosemary» содержит в
        // себе «rose», и в обратном порядке ярлык розмарина попадал бы на
        // розу. Правило простое — слово, внутри которого есть другое
        // слово списка, стоит выше него.
        ("rosemary", "Розмарин", 5.9),
        ("rose", "Роза", 5),
        ("lily", "Лилия", 6),
        ("daisy", "Ромашка", 5),
        ("sunflower", "Подсолнух", 4),
        ("geranium", "Пеларгония", 5.4),
        ("begonia", "Бегония", 6.2),
        ("basil", "Базилик", 3.8),
        ("mint", "Мята", 4.2),
        ("herb", "Зелень", 4),
        ("moss", "Мох", 3),
        ("seedling", "Росток", 4),
        ("bush", "Кустик", 8),
        ("shrub", "Кустик", 8),
        ("tree", "Деревце", 12),
        ("grass", "Трава", 4),
        ("houseplant", "Комнатное растение", 7),
        ("flower", "Цветок", 5),
        ("leaf", "Комнатное растение", 7),
        ("plant", "Комнатное растение", 7),
    ]

    /// Ниже этой уверенности ярлык в расчёт не берётся.
    ///
    /// Порог низкий, и так и надо: классификатор раздаёт уверенность на
    /// тысячи ярлыков сразу, и даже верный редко берёт больше трети.
    /// Слишком высокий порог отсёк бы всё, кроме «plant», — то есть ровно
    /// то, ради чего затея и не нужна.
    static let floor = 0.06

    /// Что из увиденного похоже на растение.
    ///
    /// Пусто — значит, ни одного знакомого слова: на снимке может не быть
    /// растения вовсе, и придумывать вид в таком случае нечестно. Экран
    /// тогда просто оставляет поля пустыми.
    static func read(_ seen: [Sighting], floor: Double = Species.floor)
        -> Guess? {
        let strong = seen.filter { $0.confidence >= floor }
        for entry in table {
            // Наблюдения приходят от самого уверенного к самому слабому,
            // поэтому первое найденное — самое уверенное с этим словом.
            guard let hit = strong.first(where: {
                $0.name.lowercased().contains(entry.word)
            }) else { continue }
            return Guess(species: entry.species, dryingDays: entry.days,
                         confidence: hit.confidence)
        }
        return nil
    }

    /// Насколько часто поливать — на выбор. Не ползунок: разница между
    /// шестью и семью сутками никому не важна, а между тремя и тридцатью
    /// важна очень, и шагом в сутки до тридцати пришлось бы крутить долго.
    static let periods: [Double] = [3, 5, 7, 10, 14, 21, 30, 60]

    /// Ближайший срок из списка — в него и встаёт подсказка.
    static func period(near days: Double) -> Double {
        periods.min { abs($0 - days) < abs($1 - days) } ?? 7
    }

    /// «Раз в 7 дней».
    static func periodLabel(_ days: Double) -> String {
        let whole = Int(days.rounded())
        return "Раз в \(whole) "
            + Plant.plural(whole, "день", "дня", "дней")
    }
}
