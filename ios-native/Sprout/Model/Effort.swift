import Foundation

/// Сколько работы в сборке модели — по виду и детализации, в единицах
/// `Meter` (примерно наносекунды). Замерено на готовых моделях. У моделей
/// по снимку работа почти та же, а где больше — проценты постоят чуть
/// дольше перед концом. Поменялись рецепты или растеризатор — проверка
/// модели скажет об этом и напечатает таблицу заново.
enum Effort {
    static func expected(_ preset: Preset, _ detail: Rig.Detail) -> Int {
        let tier = Rig.Tier.allCases.first { Rig.Detail.of($0) == detail }
        if let tier, let row = table[preset] { return row[tier.rawValue] }
        // Детализация не из трёх известных — от обычной, по площади
        // рисунков.
        let base = table[preset]?[Rig.Tier.standard.rawValue] ?? 60_000_000
        return Int(Double(base) * Double(detail.texture * detail.texture))
    }

    /// Бережная, обычная и полная детализация — см. `Rig.Detail.of`.
    static let table: [Preset: [Int]] = [
        .monstera: [74_807_592, 212_898_574, 441_847_888],
        .ficus: [36_654_828, 62_689_020, 105_556_176],
        .sansevieria: [28_174_556, 33_525_588, 41_578_060],
        .zamioculcas: [30_397_448, 38_458_748, 52_140_884],
        .spathiphyllum: [35_970_956, 58_808_358, 97_011_530],
        .orchid: [43_533_194, 90_238_498, 165_235_860],
        .aloe: [46_446_110, 46_446_110, 46_446_110],
        .cactus: [40_115_200, 44_706_396, 52_842_652],
        .echeveria: [33_384_370, 33_384_370, 33_384_370],
        .jade: [31_146_676, 31_180_926, 31_233_676],
        .dracaena: [29_359_322, 32_263_302, 36_894_202],
        .palm: [29_831_720, 30_901_040, 32_826_352],
        .fern: [67_951_464, 67_951_464, 67_951_464],
        .ivy: [33_410_654, 53_305_916, 86_933_068],
        .chlorophytum: [28_631_516, 31_434_506, 35_595_906],
        .violet: [36_987_238, 65_766_746, 113_084_462],
        .begonia: [42_559_438, 86_375_546, 157_305_112],
        .pelargonium: [41_975_858, 85_129_282, 156_224_158],
        .herbs: [28_121_280, 33_318_038, 41_774_606],
