import Foundation
import Observation

/// Кутерьма: что творится с узором, пока она идёт.
///
/// Затрясли телефон — и узор пускается вразнос: фигурки волной сжимаются
/// до нуля и вырастают обратно уже другими, и с каждым тактом весь узор
/// перекрашивается в новый цвет. Через несколько тактов всё само
/// возвращается к тому набору и тому цвету, что выбраны в настройках.
///
/// Такты идут не разом по всему экрану, а той же волной, что и всё
/// остальное: фигурка отстаёт от середины ровно на свой черёд. Оттого на
/// экране в любой миг видно кольцо — впереди ещё прежний такт, позади уже
/// следующий.
///
/// Здесь одна арифметика: такт, доля внутри него и размер фигурки. Что
/// рисовать, решает узор.
struct Frolic: Sendable {
    /// Сколько секунд кутерьма уже идёт.
    var elapsed: Double

    /// Сколько длится один такт и сколько их всего.
    ///
    /// Такт короткий: фигурка успевает сжаться и вырасти за 0.7 секунды, и
    /// смены идут одна за другой, а не вяло сменяют друг друга. Тактов
    /// шесть — пять беспорядочных и шестой, которым узор садится обратно.
    static let beat = 0.7
    static let beats = 6

    /// Сколько всего длится кутерьма.
    ///
    /// На такт больше, чем тактов: дальняя фигурка трогается с места
    /// ровно на такт позже ближней, и ей нужно столько же времени, чтобы
    /// доиграть.
    static var seconds: Double { Double(beats + 1) * beat }

    /// В каком состоянии фигурка с таким черёдом и насколько она сжата.
    ///
    /// Состояние — номер «какой узор показывать». Ноль и последнее — тот
    /// самый, что выбран в настройках: кутерьма начинается с него и им же
    /// кончается. Между ними беспорядок.
    ///
    /// Проход у фигурки тот же, что при смене набора: первая половина
    /// такта она сжимается до нуля в прежнем состоянии, вторая — растёт
    /// из нуля уже в следующем. Обе кривые у нуля крутые, поэтому сквозь
    /// ноль она проскакивает быстро и голого места на её клетке почти не
    /// бывает.
    func look(turn: Double) -> (state: Int, scale: Double) {
        let own = elapsed - min(max(turn, 0), 1) * Self.beat
        guard own > 0 else { return (0, 1) }
        let raw = own / Self.beat
        let beat = Int(raw)
        guard beat < Self.beats else { return (Self.beats, 1) }
        let part = raw - Double(beat)
        if part < 0.5 {
            let x = part * 2
            return (beat, 1 - x * x * x)
        }
        let x = (part - 0.5) * 2
        return (beat + 1, 1 - pow(1 - x, 3))
    }

    /// Беспорядочное ли это состояние. Первое и последнее — нет: это
    /// обычный узор, с которого кутерьма началась и которым кончится.
    static func chaotic(_ state: Int) -> Bool {
        state > 0 && state < beats
    }
}

/// Кутерьма как событие: когда началась и сколько ей осталось.
///
/// Заводится тряской телефона — см. `Tilt`. Одна на приложение, как волна
/// полива, и по той же причине: фон рисуется в двух местах — на экране и
/// подложкой под вырезом, — и веди каждое своё время, они разошлись бы на
/// кадр-другой.
@Observable
final class Frenzy {
    static let shared = Frenzy()

    /// Когда началась. Пусто — узор в покое.
    private(set) var start: Date?

    @ObservationIgnored private var run: Task<Void, Never>?

    private init() {}

    /// Затрясли. Пока кутерьма идёт, второй раз не начинаем: трясти
    /// продолжают и после того, как она пошла.
    ///
    /// Отвечает, тронулась ли: отклик в руке должен пойти вместе с ней, а
    /// не на каждое подряд встряхивание.
    @discardableResult
    func begin(at moment: Date = Date()) -> Bool {
        guard start == nil else { return false }
        start = moment
        run?.cancel()
        run = Task { @MainActor in
            try? await Task.sleep(for: .seconds(Frolic.seconds))
            guard !Task.isCancelled else { return }
            start = nil
        }
        return true
    }

    /// Где кутерьма на этот момент. Пусто — её нет или уже отыграла.
    func frolic(at moment: Date) -> Frolic? {
        guard let start else { return nil }
        let elapsed = moment.timeIntervalSince(start)
        return elapsed < Frolic.seconds ? Frolic(elapsed: elapsed) : nil
    }
}
