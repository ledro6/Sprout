import Foundation

/// Фигурки узора плавают в вязкой среде, пока узор едет за наклоном.
///
/// За наклоном телефона узор едет одним куском: холст сдвигается целиком,
/// и пересобирать его ради этого не нужно — см. `Tilt`. Но кусок этот и
/// читается куском: расстояния между соседями не меняются ни на волос, и
/// за экраном выходит не глубина, а наклеенная плёнка.
///
/// Здесь узор перестаёт быть куском. Фигурки разложены по нескольким
/// слоям, и каждый слой догоняет наклон со своей вязкостью: лёгкий уходит
/// вперёд, тяжёлый отстаёт. Пока телефон качают, слои разъезжаются, и
/// фигурки то сходятся с соседями, то расходятся. Отпустили — слои
/// сходятся обратно, и фигурки доплывают на своей инерции, а не встают
/// как вкопанные. Самое заметное движение приходится как раз на после
/// наклона: это и есть «густая среда».
///
/// Прежде здесь была не вязкость, а постоянная доля общего сдвига у
/// каждой фигурки. Разъезд выходил, но мёртвый: фигурка всегда обгоняла
/// ровно на столько же, инерции не было вовсе, и плыли всегда одни и те
/// же. Теперь слой достаётся фигурке жребием, и жребий перебрасывается —
/// см. `shuffleSeconds`.
enum Sway {
    /// Насколько слой догоняет наклон за кадр.
    ///
    /// Середина списка равна вязкости самого узора (`Tilt.ease`, 0.12):
    /// фигурки этого слоя идут с ним вровень и не сдвигаются никуда.
    /// Слева от неё — лёгкие, они обгоняют; справа — тяжёлые, отстают.
    /// Так разъезд идёт в обе стороны от узора, а не только назад.
    ///
    /// Самый тяжёлый слой успокаивается за 1/0.045 ≈ 22 кадра, то есть
    /// чуть больше трети секунды после того, как телефон замер. Это и
    /// есть доплывание.
    static let eases: [Double] = [0.24, 0.17, 0.12, 0.075, 0.045]

    /// Дальше этого фигурка от своего места не уходит.
    ///
    /// Упор нужен не ради красоты, а ради порядка: между серединами
    /// соседних фигурок 45 pt, и без него резкий взмах развёл бы их
    /// настолько, что узор перестал бы быть узором.
    static let limit: CGFloat = 7

    /// Сколько секунд покоя нужно, чтобы перебросить жребий.
    ///
    /// Перебрасывается он только в покое, и это не прихоть: слой у
    /// фигурки — это её вязкость, и смена вязкости на ходу дёрнула бы
    /// фигурку скачком. В покое же слои сошлись, разъезд у всех нулевой,
    /// и подмена не видна вовсе.
    static let shuffleSeconds = 0.9

    /// В каком слое плывёт эта фигурка в этот заход.
    ///
    /// Жребий берётся от места фигурки в сетке и от номера захода: внутри
    /// захода он неизменен — иначе фигурка дрожала бы на месте, — а от
    /// захода к заходу меняется, и плывут каждый раз другие.
    static func layer(column: Int, row: Int, slot: Int, era: Int) -> Int {
        let part = (noise(column, row, slot, axis: era &* 2 &+ 7) + 1) / 2
        return min(max(Int(part * CGFloat(eases.count)), 0), eases.count - 1)
    }

    /// Один шаг вязкости: каждый слой подтягивается к своей цели.
    ///
    /// Цель у всех слоёв одна и та же — та, к которой идёт и сам узор.
    /// Разъезд берётся не из разных целей, а из разной скорости.
    static func settle(_ places: [CGSize], toward target: CGSize) -> [CGSize] {
        var next = places
        for i in next.indices where i < eases.count {
            let ease = CGFloat(eases[i])
            next[i] = CGSize(
                width: next[i].width + (target.width - next[i].width) * ease,
                height: next[i].height + (target.height - next[i].height) * ease)
        }
        return next
    }

    /// Насколько каждый слой разошёлся с узором — на это и сдвигаются
    /// его фигурки.
    static func lag(_ places: [CGSize], behind common: CGSize) -> [CGSize] {
        places.map { place in
            CGSize(width: hold(place.width - common.width),
                   height: hold(place.height - common.height))
        }
    }

    /// Слои в начале: все стоят там же, где узор, и разъезда нет.
    static func rest(at place: CGSize) -> [CGSize] {
        Array(repeating: place, count: eases.count)
    }

    private static func hold(_ value: CGFloat) -> CGFloat {
        min(max(value, -limit), limit)
    }

    /// Ровный шум −1…1 по месту фигурки в сетке и номеру захода.
    ///
    /// Тот же замес, что у `scramble` в узоре: разряды перемешиваются
    /// умножением на простые и сдвигом. Случайности здесь не нужно —
    /// нужен один и тот же жребий у одной и той же фигурки во всех кадрах
    /// одного захода.
    static func noise(_ column: Int, _ row: Int, _ slot: Int,
                      axis: Int) -> CGFloat {
        var mix = column &* 73_856_093
        mix ^= row &* 19_349_663
        mix ^= slot &* 83_492_791
        mix ^= axis &* 2_654_435_761
        mix ^= mix >> 13
        mix = mix &* 1_274_126_177
        mix ^= mix >> 16
        return CGFloat(mix & 0xFFFF) / CGFloat(0xFFFF) * 2 - 1
    }
}
