import Foundation

/// Разъезд фигурок узора при параллаксе.
///
/// За наклоном телефона узор едет одним куском: холст сдвигается целиком,
/// и пересобирать его ради этого не нужно — см. `Tilt`. Но кусок этот и
/// читается куском. Все фигурки идут на один и тот же сдвиг, расстояния
/// между соседями не меняются ни на волос, и глубины в таком параллаксе
/// нет: за экраном не слои, а одна наклеенная плёнка.
///
/// Здесь у каждой фигурки заводится своя доля общего сдвига. Доля больше
/// нуля — фигурка обгоняет узор и подходит к соседу, меньше — отстаёт и
/// отходит. Качнули телефон обратно — подошедшая отходит ровно настолько
/// же: доля у фигурки одна и та же, а знак задаёт сам наклон.
///
/// Разъезд должно быть видно: в нём вся затея. Но видно именно разъезд, а
/// не съехавшую сетку — поэтому размах у фигурки меньше просвета между
/// соседями в разы, и ни одна не наезжает на чужое место.
///
/// Выключается в настройках, отдельно от самого параллакса: движение фона
/// мешает не всем и не одинаково.
enum Sway {
    /// Наибольшая доля общего сдвига, которую фигурка берёт сверх него.
    ///
    /// При размахе параллакса в 14 pt это 4.2 pt на фигурку в крайнем
    /// положении, то есть до восьми между двумя соседями, разошедшимися в
    /// разные стороны. Между серединами соседних фигурок 45 pt, так что
    /// просвет между ними гуляет на пятую часть — этого и хотели: должно
    /// быть видно, что фигурки живут порознь, а не едут доской.
    ///
    /// Первым заходом здесь стояло 0.09, и разъезд выходил честным, но
    /// незаметным: полтора пункта на фигурку глаз не ловит.
    static let share: CGFloat = 0.3

    /// Доля этой фигурки по обеим осям, −1…1.
    ///
    /// Две доли, по одной на ось, а не одна на обе: с одной фигурки
    /// ходили бы строго по диагонали, и разъезд читался бы строем.
    ///
    /// Число берётся квадратом ровного шума со своим знаком. Квадрат
    /// подбирает доли к нулю, но не так круто, как куб: у куба почти
    /// половина фигурок стояла неподвижно, и разъезд читался редкими
    /// выскочками. У квадрата без места остаётся треть, а у трети —
    /// добрая половина размаха: видно, что порознь живёт каждая, а не
    /// пять штук на экран.
    ///
    /// Совсем без подбора, на ровном шуме, разошлись бы все разом и в
    /// полную силу — узор читался бы не глубиной, а дрожью.
    static func of(column: Int, row: Int, slot: Int) -> (x: CGFloat, y: CGFloat) {
        (curve(noise(column, row, slot, axis: 0)),
         curve(noise(column, row, slot, axis: 1)))
    }

    /// Поправка к месту фигурки при таком общем сдвиге.
    static func drift(_ shift: CGSize,
                      column: Int, row: Int, slot: Int) -> CGSize {
        let part = of(column: column, row: row, slot: slot)
        return CGSize(width: shift.width * share * part.x,
                      height: shift.height * share * part.y)
    }

    /// Квадрат со знаком: знак берётся у самого шума, сила — у квадрата.
    private static func curve(_ value: CGFloat) -> CGFloat {
        value * abs(value)
    }

    /// Ровный шум −1…1 по месту фигурки в сетке.
    ///
    /// Тот же замес, что у `scramble` в узоре: разряды перемешиваются
    /// умножением на простые и сдвигом. Случайности здесь не нужно —
    /// нужна одна и та же доля у одной и той же фигурки во всех кадрах,
    /// иначе фигурка дрожала бы на месте вместо того, чтобы стоять в
    /// своём слое.
    static func noise(_ column: Int, _ row: Int, _ slot: Int,
                      axis: Int) -> CGFloat {
        var mix = column &* 73_856_093
        mix ^= row &* 19_349_663
        mix ^= slot &* 83_492_791
        mix ^= axis &* 2_654_435_761
        mix ^= mix >> 13
        mix = mix &* 1_274_126_177
        mix ^= mix >> 16
        return CGFloat(mix & 0xFFFF) / CGFloat(0xFFFF) * 2 - 1
    }
}
