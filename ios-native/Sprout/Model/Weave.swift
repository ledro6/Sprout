import Foundation

/// Раскладка узора: какая из выбранных фигурок стоит в узле сетки.
///
/// Правило простое: номер фигурки меняется на постоянную величину при
/// шаге вбок и на другую постоянную при шаге вниз. Пока обе не делятся
/// нацело на число фигурок, две одинаковые не могут оказаться соседями —
/// ни по горизонтали, ни по вертикали. Величины на каждый запуск свои,
/// поэтому и раскладка каждый раз новая.
///
/// Шаги берутся взаимно простыми с числом фигурок, а не любыми
/// подходящими. Двойка при четырёх фигурках соседство не нарушает, но
/// в ряду оставляет только две фигурки из четырёх, через одну, — узор
/// вырождается в полосы. Взаимно простой шаг обходит все фигурки по
/// очереди.
///
/// Раскладок отсюда: при двух фигурках две, при трёх двенадцать, при
/// четырёх шестнадцать. Две — не оплошность и не лень: у сетки, где
/// соседи обязаны различаться, двухцветных раскладок ровно две, шахматная
/// и она же со сдвигом на клетку. Больше взять неоткуда.
///
/// Одна фигурка — раскладки нет вовсе: соседство одинаковых там
/// неизбежно и ничему не мешает.
///
/// Ценой этого поменялся узор макета. В макете росток и капля стоят
/// столбиками — над ростком росток, — то есть ровно то, что новое правило
/// запрещает. Теперь они в шахматном порядке.
struct Weave: Equatable {
    /// На сколько сдвигается номер фигурки при шаге вбок и вниз.
    var stepX = 1
    var stepY = 1

    /// С какой фигурки начинается отсчёт.
    var shift = 0

    /// Раскладка «всё одинаковое» — для единственной фигурки.
    init() {}

    /// Раскладка из трёх чисел, выбранных на запуск.
    init(count: Int, twistX: Int, twistY: Int, start: Int) {
        guard count > 1 else { return }
        let steps = (1 ..< count).filter { Self.divisor($0, count) == 1 }
        stepX = steps[abs(twistX) % steps.count]
        stepY = steps[abs(twistY) % steps.count]
        shift = abs(start) % count
    }

    /// Номер фигурки в этом узле сетки.
    ///
    /// Узлы в ряду нумеруются сплошь: `2·столбец + гнездо`, потому что в
    /// ячейке узора два гнезда.
    func index(column: Int, slot: Int, row: Int, of count: Int) -> Int {
        guard count > 1 else { return 0 }
        let node = 2 * column + slot
        let raw = (stepX * node + stepY * row + shift) % count
        return raw < 0 ? raw + count : raw
    }

    private static func divisor(_ a: Int, _ b: Int) -> Int {
        b == 0 ? a : divisor(b, a % b)
    }
}
