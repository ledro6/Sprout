import Foundation

/// Оттенок, которым рисуется узор или его волна.
///
/// У каждого две ипостаси: бледная и насыщенная. Бледной узор лежит в
/// покое — он фон, и заметным быть не должен; насыщенной идёт волна
/// полива и её свечение — это событие, и оно должно читаться с угла
/// глаза. Один и тот же оттенок годится и туда и туда: разнятся у них не
/// цвета, а доли, и доли эти задаёт не оттенок, а место, где он лежит,
/// — см. `Palette`.
///
/// Тема сюда не заходит вовсе. Каналы одни на светлую и на тёмную, а
/// разницу между ними целиком берут на себя те же доли: на белом узор
/// кладётся в 42%, на сером — в 8%, потому что светлое на тёмном
/// заметнее, чем светлое на светлом.
///
/// Живёт в модели, а не в палитре: здесь одни числа, и их можно
/// прогнать где угодно, где есть Swift. Палитра из них уже делает цвета,
/// а `Color` есть только на платформах Apple.
enum Tint: Int, CaseIterable, Identifiable, Sendable {
    case green, blue, violet, amber, rose

    var id: Int { rawValue }

    /// Зелёный первым и он же по умолчанию у узора: это цвет макета.
    /// Синий по умолчанию у волны — тот, которым полив отмечался с самого
    /// начала.
    static let defaultPattern = Tint.green
    static let defaultWave = Tint.blue

    var title: String {
        switch self {
        case .green: "Зелёный"
        case .blue: "Синий"
        case .violet: "Сиреневый"
        case .amber: "Медовый"
        case .rose: "Розовый"
        }
    }

    /// Бледная ипостась — ею узор лежит в покое. Каналы 0…255.
    ///
    /// Зелёный здесь макетный, #CFF8C9. Остальные не подобраны на глаз, а
    /// посчитаны: каждый — своя насыщенная ипостась, подтянутая к белому
    /// ровно настолько, чтобы светлота сошлась с макетным зелёным, 0.925
    /// по формуле для sRGB. Светлота решает, насколько узор заметен на
    /// фоне; разойдись она — смена цвета меняла бы не только цвет, но и
    /// то, насколько узор лезет в глаза. Разброс держится в двух тысячных
    /// и проверяется прогоном модели.
    var pale: Channels {
        switch self {
        case .green: Channels(207, 248, 201)
        case .blue: Channels(222, 238, 255)
        case .violet: Channels(240, 233, 254)
        case .amber: Channels(255, 233, 208)
        case .rose: Channels(255, 230, 236)
        }
    }

    /// Насыщенная — ею идёт волна полива, свечение под ней и весь узор в
    /// тёмной теме.
    ///
    /// Все взяты в девять десятых насыщенности и выше. Сперва здесь были
    /// цвета помягче — зелёный из логотипа, системный сиреневый iOS, — и
    /// на волне они читались не вспышкой, а подцветкой: гребень должен
    /// быть виден с угла глаза. Синий не тронут: он и был на пределе,
    /// это чистый системный #007AFF.
    ///
    /// Графит отсюда убран совсем. Серый в наборе цветов — это выбор «без
    /// цвета», и на волне он не читался вовсе.
    var vivid: Channels {
        switch self {
        case .green: Channels(10, 199, 51)
        case .blue: Channels(0, 122, 255)
        case .violet: Channels(97, 24, 242)
        case .amber: Channels(255, 136, 0)
        case .rose: Channels(255, 13, 73)
        }
    }
}

/// Цвет каналами 0…255 — без `Color`, чтобы жить в модели.
struct Channels: Hashable, Sendable {
    var red: Double
    var green: Double
    var blue: Double

    init(_ red: Double, _ green: Double, _ blue: Double) {
        self.red = red
        self.green = green
        self.blue = blue
    }

    /// Смесь двух цветов: ноль — первый, единица — второй.
    static func mix(_ from: Channels, _ to: Channels, _ k: Double) -> Channels {
        let part = min(max(k, 0), 1)
        return Channels(from.red + (to.red - from.red) * part,
                        from.green + (to.green - from.green) * part,
                        from.blue + (to.blue - from.blue) * part)
    }
}

/// Оттенок, готовый к рисованию: обе ипостаси каналами.
///
/// Отдельно от `Tint`, потому что во время смены цвета на экране лежит не
/// оттенок из списка, а смесь двух — и у неё номера в списке нет.
///
/// Смешиваются ипостаси по отдельности, каждая со своей: бледная с
/// бледной, насыщенная с насыщенной. Иначе на середине перехода узор
/// сходил бы к серому — смешай зелёную бледную с розовой насыщенной, и
/// получишь ровно его.
struct Shade: Equatable, Sendable {
    var pale: Channels
    var vivid: Channels

    init(_ tint: Tint) {
        pale = tint.pale
        vivid = tint.vivid
    }

    init(pale: Channels, vivid: Channels) {
        self.pale = pale
        self.vivid = vivid
    }

    static func mix(_ from: Shade, _ to: Shade, _ k: Double) -> Shade {
        Shade(pale: .mix(from.pale, to.pale, k),
              vivid: .mix(from.vivid, to.vivid, k))
    }
}
