import Foundation

/// Оттенок, которым рисуется узор или его волна.
///
/// У каждого две ипостаси: бледная и насыщенная. Бледной узор лежит в
/// покое — он фон, и заметным быть не должен; насыщенной идёт волна
/// полива и её свечение — это событие, и оно должно читаться с угла
/// глаза. Один и тот же оттенок годится и туда и туда: разнятся у них не
/// цвета, а доли, и доли эти задаёт не оттенок, а место, где он лежит,
/// — см. `Palette`.
///
/// Тема сюда не заходит вовсе. Каналы одни на светлую и на тёмную, а
/// разницу между ними целиком берут на себя те же доли: на белом узор
/// кладётся в 42%, на сером — в 8%, потому что светлое на тёмном
/// заметнее, чем светлое на светлом.
///
/// Живёт в модели, а не в палитре: здесь одни числа, и их можно
/// прогнать где угодно, где есть Swift. Палитра из них уже делает цвета,
/// а `Color` есть только на платформах Apple.
enum Tint: Int, CaseIterable, Identifiable, Sendable {
    case green, blue, violet, amber, rose, graphite

    var id: Int { rawValue }

    /// Зелёный первым и он же по умолчанию у узора: это цвет макета.
    /// Синий по умолчанию у волны — тот, которым полив отмечался с самого
    /// начала.
    static let defaultPattern = Tint.green
    static let defaultWave = Tint.blue

    var title: String {
        switch self {
        case .green: "Зелёный"
        case .blue: "Синий"
        case .violet: "Сиреневый"
        case .amber: "Медовый"
        case .rose: "Розовый"
        case .graphite: "Графит"
        }
    }

    /// Бледная ипостась — ею узор лежит в покое. Каналы 0…255.
    ///
    /// Зелёный здесь макетный, #CFF8C9. Остальные не подобраны на глаз, а
    /// посчитаны: каждый — своя насыщенная ипостась, подтянутая к белому
    /// ровно настолько, чтобы светлота сошлась с макетным зелёным, 0.925
    /// по формуле для sRGB. Светлота решает, насколько узор заметен на
    /// фоне; разойдись она — смена цвета меняла бы не только цвет, но и
    /// то, насколько узор лезет в глаза. Разброс держится в двух тысячных
    /// и проверяется прогоном модели.
    var pale: Channels {
        switch self {
        case .green: Channels(207, 248, 201)
        case .blue: Channels(222, 238, 255)
        case .violet: Channels(239, 233, 252)
        case .amber: Channels(255, 234, 201)
        case .rose: Channels(255, 230, 235)
        case .graphite: Channels(235, 236, 237)
        }
    }

    /// Насыщенная — ею идёт волна полива и свечение под ней.
    ///
    /// Взяты системные цвета iOS, кроме зелёного: тот из логотипа
    /// приложения.
    var vivid: Channels {
        switch self {
        case .green: Channels(55, 181, 81)
        case .blue: Channels(0, 122, 255)
        case .violet: Channels(132, 82, 235)
        case .amber: Channels(255, 159, 10)
        case .rose: Channels(255, 55, 95)
        case .graphite: Channels(99, 105, 112)
        }
    }
}

/// Цвет каналами 0…255 — без `Color`, чтобы жить в модели.
struct Channels: Hashable, Sendable {
    var red: Double
    var green: Double
    var blue: Double

    init(_ red: Double, _ green: Double, _ blue: Double) {
        self.red = red
        self.green = green
        self.blue = blue
    }
}
