import Foundation

/// Один полив — одна запись. Растение полили кнопкой, а через пять минут
/// датчик увидел подскок; полили двое из семьи, не зная друг о друге, —
/// в журнале всё равно один полив: серия, счёт и статистика не считают
/// воду дважды. Одна проверка на все пути — кнопку, датчик и общий сад.
enum Twin {
    /// Окно, в котором второй полив того же растения — тот же полив.
    static let window: TimeInterval = 10 * 60

    /// Номер записи о поливе того же растения в пределах окна от `when` —
    /// в обе стороны: запись может прийти и задним числом.
    static func index(_ plant: Plant.ID, at when: Date, in log: [Watering],
                      within span: TimeInterval = window) -> Int? {
        log.lastIndex {
            $0.plant == plant && abs($0.when.timeIntervalSince(when)) < span
        }
    }

    /// Какую из двух записей-близнецов оставить: раннюю, при равенстве — с
    /// меньшим номером. Правило одно на всех телефонах семьи, поэтому сад
    /// сходится к одной и той же записи, с какой стороны ни смотри.
    static func keeps(_ a: Watering, over b: Watering) -> Bool {
        if a.when != b.when { return a.when < b.when }
        return (a.id ?? "") < (b.id ?? "")
    }
}
