import Foundation

/// Откуда по узору расходится переход.
///
/// Переходов у узора четыре — всходы при запуске, смена набора фигурок,
/// смена цвета и волна полива, — и все они устроены одинаково: у каждой
/// фигурки свой черёд, а разнятся они только тем, в каком порядке этот
/// черёд раздаётся. Здесь и лежит этот порядок, отдельно от самих
/// переходов.
///
/// Черёд — доля от нуля до единицы: ноль у фигурки, с которой всё
/// начинается, единица у самой дальней. Что с фигуркой делать, когда до
/// неё дошло, фронт не знает и знать не должен: одному переходу расти,
/// другому перекрашиваться.
///
/// Живёт в модели: тут одна геометрия, и её можно прогнать где угодно,
/// где есть Swift.
enum Front: Equatable, Sendable {
    /// Из точки наружу, кругами. Точка — в координатах холста узора.
    ///
    /// Так расходятся волна полива и всё, что хозяин выбрал пальцем:
    /// переход начинается ровно там, где палец, и это единственное место
    /// на экране, куда хозяин в тот миг смотрит.
    case point(CGPoint)

    /// С краёв экрана внутрь.
    ///
    /// Обратная точке: первыми идут фигурки у кромки, последними — в
    /// середине. Ею уходит то, что убрали: выбранное приходит оттуда, где
    /// его выбрали, а уходящему приходить неоткуда, и оно сходит с краёв.
    case edges

    /// Полосой, в заданную сторону. Угол в радианах.
    ///
    /// Угол — куда фронт идёт, а начинается он с противоположной
    /// стороны: направь его вверх, и первыми пойдут нижние фигурки.
    ///
    /// Ею всходит узор при запуске. Ею же прежде менялся набор фигурок —
    /// см. «Точки возврата» в README.
    case sweep(Double)

    /// Черёд фигурки, стоящей в этой точке холста.
    func turn(at middle: CGPoint, over size: CGSize) -> Double {
        let width = max(Double(size.width), 1)
        let height = max(Double(size.height), 1)
        let x = Double(middle.x), y = Double(middle.y)

        switch self {
        case let .point(from):
            // Мерка — расстояние до самого дальнего угла холста. Не общая
            // на все точки: от угла до угла дальше, чем от середины, и с
            // общей меркой переход из угла не успевал бы дойти до
            // противоположного за отведённое время.
            let dx = Double(from.x), dy = Double(from.y)
            let reach = max(hypot(dx, dy), hypot(width - dx, dy),
                            hypot(dx, height - dy),
                            hypot(width - dx, height - dy))
            return min(hypot(x - dx, y - dy) / max(reach, 1), 1)

        case .edges:
            // Расстояние до ближайшей кромки, растянутое на полширины
            // холста: у кромки ноль, в середине единица.
            let near = min(min(x, width - x), min(y, height - y))
            return min(max(near, 0) / max(min(width, height) / 2, 1), 1)

        case let .sweep(angle):
            let dx = cos(angle), dy = sin(angle)
            // Проекция на направление, растянутая на весь ход. У косого
            // направления размах шире, чем у прямого, и без пересчёта
            // часть хода уходила бы впустую.
            let reach = (abs(dx) + abs(dy)) / 2
            let along = (x / width - 0.5) * dx + (y / height - 0.5) * dy
            return min(max(along / (2 * reach) + 0.5, 0), 1)
        }
    }
}
