import Foundation

/// Откуда по узору расходится переход.
///
/// Переходов у узора четыре — всходы при запуске, смена набора фигурок,
/// смена цвета и волна полива, — и все они устроены одинаково: у каждой
/// фигурки свой черёд, а разнятся они только тем, в каком порядке этот
/// черёд раздаётся. Здесь и лежит этот порядок, отдельно от самих
/// переходов.
///
/// Черёд — доля от нуля до единицы: ноль у фигурки, с которой всё
/// начинается, единица у самой дальней. Что с фигуркой делать, когда до
/// неё дошло, фронт не знает и знать не должен: одному переходу расти,
/// другому перекрашиваться.
///
/// Живёт в модели: тут одна геометрия, и её можно прогнать где угодно,
/// где есть Swift.
enum Front: Equatable, Sendable {
    /// Сколько пунктов фронт проходит за отведённое ему время.
    ///
    /// Общая мерка на все переходы, и в этом весь смысл. Прежде круговой
    /// фронт мерился расстоянием до самого дальнего угла холста — то есть
    /// у перехода из середины скорость была одна, у перехода из угла
    /// другая, а у волны полива третья, своя. Три разные скорости читались
    /// тремя разными анимациями, хотя должны читаться одной.
    ///
    /// Число то же, что у волны полива, и больше диагонали экрана: до
    /// дальнего угла фронт добирается, даже если тронулся из
    /// противоположного.
    static let reach: Double = 900

    /// Из точки наружу, кругами. Точка — в координатах холста узора.
    ///
    /// Так расходятся волна полива и всё, что хозяин выбрал пальцем:
    /// переход начинается ровно там, где палец, и это единственное место
    /// на экране, куда хозяин в тот миг смотрит.
    case point(CGPoint)

    /// В точку снаружи, кругами. Та же волна, пущенная вспять.
    ///
    /// Первыми идут дальние фигурки, последней — та, что стоит на самой
    /// точке. Ею уходит то, что убрали: волна сбегается и садится ровно
    /// туда, где нажали.
    ///
    /// Мерка у неё своя — расстояние до самого дальнего угла холста, а не
    /// общие `reach`. С общей выходила задержка: если до дальнего угла
    /// экрана пятьсот пунктов, а мерка девятьсот, то полдоли черёда
    /// приходилось на то, чего не видно, и почти полсекунды после нажатия
    /// на экране не двигалось ничего. Со своей меркой самая дальняя
    /// видимая фигурка трогается ровно в ноль.
    ///
    /// Прежде здесь был `edges` — «с краёв экрана внутрь». Он мерил
    /// расстояние до ближайшей кромки, а линии равного расстояния до
    /// кромки прямоугольника — это прямоугольники: фронт шёл по экрану
    /// стягивающейся рамкой, и волной не читался вовсе.
    case collapse(CGPoint)

    /// Полосой, в заданную сторону. Угол в радианах.
    ///
    /// Угол — куда фронт идёт, а начинается он с противоположной
    /// стороны: направь его вверх, и первыми пойдут нижние фигурки.
    ///
    /// Ею всходит узор при запуске. Ею же прежде менялся набор фигурок —
    /// см. «Точки возврата» в README.
    case sweep(Double)

    /// Черёд фигурки, стоящей в этой точке холста.
    func turn(at middle: CGPoint, over size: CGSize) -> Double {
        let width = max(Double(size.width), 1)
        let height = max(Double(size.height), 1)
        let x = Double(middle.x), y = Double(middle.y)

        switch self {
        case let .point(from):
            return Self.away(from, x, y)

        case let .collapse(into):
            // Дальние первыми, сама точка последней — и «дальние» здесь
            // значит «дальние на этом холсте», а не «за девятьсот
            // пунктов»: см. описание.
            let dx = Double(into.x), dy = Double(into.y)
            let corner = max(hypot(dx, dy), hypot(width - dx, dy),
                             hypot(dx, height - dy),
                             hypot(width - dx, height - dy))
            let far = hypot(x - dx, y - dy)
            return 1 - min(far / max(corner, 1), 1)

        case let .sweep(angle):
            let dx = cos(angle), dy = sin(angle)
            // Проекция на направление, растянутая на весь ход. У косого
            // направления размах шире, чем у прямого, и без пересчёта
            // часть хода уходила бы впустую.
            let reach = (abs(dx) + abs(dy)) / 2
            let along = (x / width - 0.5) * dx + (y / height - 0.5) * dy
            return min(max(along / (2 * reach) + 0.5, 0), 1)
        }
    }

    /// Доля пути от точки до этого места, 0…1. Дальше `reach` — единица.
    private static func away(_ from: CGPoint, _ x: Double,
                             _ y: Double) -> Double {
        let far = hypot(x - Double(from.x), y - Double(from.y))
        return min(far / Self.reach, 1)
    }
}
