import Foundation
import FoundationModels

/// Подсказчик: языковая модель Apple, живущая прямо в телефоне.
///
/// Та самая, на которой работает Apple Intelligence. Считает на месте, без
/// сети и без учётной записи, и ничего не отправляет наружу — иначе ей
/// здесь было бы не место: политика конфиденциальности Sprout обещает, что
/// приложение не выходит в сеть вовсе.
///
/// Работает не везде, и притворяться, что везде, нельзя: модели нужен
/// iPhone 15 Pro или новее — то есть A17 Pro — и включённый Apple
/// Intelligence. На iPhone 13 Pro её не будет никогда, и экран в этом
/// случае не показывает подсказок вовсе, а не показывает кнопку, которая
/// не работает.
enum Muse {
    /// Есть ли модель на этом телефоне и готова ли она отвечать.
    ///
    /// Спрашивается один раз: читают это из тела экрана, то есть на
    /// каждой перерисовке, а ответ за сеанс не меняется — модель либо
    /// есть в телефоне, либо её там не будет никогда.
    static let ready: Bool = {
        if case .available = SystemLanguageModel.default.availability {
            return true
        }
        return false
    }()

    /// Придумать кличку растению.
    ///
    /// Одну, а не список: выбирать из пяти вымученных кличек хуже, чем
    /// нажать «ещё раз» и получить новую. Оттого и просим коротко.
    static func nickname(for species: String) async -> String? {
        let answer = await say("""
        Придумай одну короткую ласковую кличку для комнатного растения \
        вида «\(species)». Кличка должна быть по-русски, одним словом, с \
        большой буквы, годиться домашнему любимцу и не повторять название \
        вида. Ответь только кличкой, без кавычек и без пояснений.
        """)
        // Модель иногда всё же добавляет точку или кавычки — подчищаем.
        let word = answer?
            .trimmingCharacters(in: CharacterSet(charactersIn: " \n\t.,«»\"'"))
            .split(whereSeparator: \.isWhitespace)
            .first
        guard let word, word.count <= 24 else { return nil }
        return String(word)
    }

    /// Совет по уходу — два-три предложения, без списков и заголовков.
    static func care(for species: String) async -> String? {
        let answer = await say("""
        Дай короткий совет по уходу за комнатным растением вида \
        «\(species)»: свет, полив, чего избегать. Два-три предложения \
        по-русски, обычным текстом, без списков, заголовков и \
        вступлений.
        """)
        let text = answer?.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let text, !text.isEmpty else { return nil }
        return text
    }

    /// Спросить модель.
    ///
    /// Сеанс заводится на каждый вопрос: вопросы здесь друг с другом не
    /// связаны, и общая память между ними только сбивала бы ответ.
    ///
    /// Наставление задаёт рамку: модель общая на все задачи, и без него
    /// она отвечает как умеет — то по-английски, то абзацем с
    /// заголовками.
    private static func say(_ question: String) async -> String? {
        guard ready else { return nil }
        let session = LanguageModelSession {
            """
            Ты помощник в приложении для ухода за комнатными растениями. \
            Отвечай только по-русски, коротко и по делу. Не здоровайся, \
            не извиняйся и не объясняй, что ты делаешь.
            """
        }
        guard let reply = try? await session.respond(to: question) else {
            return nil
        }
        return reply.content
    }
}
