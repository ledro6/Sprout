import Foundation

/// Ширина имени в ленте комнат, пока лента растёт до заголовка. Чистая
/// арифметика без SwiftUI — проверяется моделью.
///
/// Ловушка, из-за которой имя сначала росло, а потом само ужималось: ширину
/// брали как «кегль сейчас, но не шире свободного места сейчас». Кегль растёт
/// с прокруткой, а свободное место с опережением съедают кнопки справа — на
/// iPhone 17 Pro (402 пункта) оно падает быстрее, чем растёт имя, и ширина
/// шла вверх, а потом вниз. Теперь концы считаются заранее — в покое и
/// доросшее, каждое в своё место, — и между ними ширина идёт прямо: только
/// растёт или только ужимается.
enum Swell {
    /// Сколько ленты при подъёме `grown` (0…1) занято кнопками: с
    /// опережением, чтобы лента не заезжала под них, поднимаясь.
    static func trail(_ corner: CGFloat, grown: CGFloat) -> CGFloat {
        corner * min(max(grown, 0) * 1.5, 1)
    }

    /// Ширина имени на экране.
    /// - natural: ширина в кегле вёрстки, он же доросший;
    /// - rest: кегль в покое долей доросшего;
    /// - fits: сколько места под имя при подъёме 0…1, с подъёмом только
    ///   убывает.
    static func width(natural: CGFloat, rest: CGFloat, grown: CGFloat,
                      fits: (CGFloat) -> CGFloat) -> CGFloat {
        let share = min(max(grown, 0), 1)
        let from = min(natural * rest, fits(0))
        let to = min(natural, fits(1))
        // Растущее имя и так не шире доросшего места; ужимающееся — вниз
        // вместе с местом, оба убывают.
        return min(from + (to - from) * share, fits(share))
    }
}
