import SwiftUI

/// Политика конфиденциальности — по тому, что приложение делает на самом
/// деле: своего сервера нет, а наружу уходит только погода и iCloud, и то
/// по включённой настройке.
struct PrivacyView: View {
    var body: some View {
        SproutPage(title: "Политика конфиденциальности") {
            // Абзац — одна строка каталога: `\` в конце строки литерала
            // склеивает её со следующей без переноса.
            Paragraph("""
                У Sprout нет ни учётной записи, ни своего сервера, ни \
                аналитики, ни рекламы. С телефона уходит только то, что \
                описано ниже в «Погоде» и «iCloud», — и только если вы это \
                включили.
                """)
            Paragraph("Что хранится", body: """
                Клички растений, виды, влажность, даты, снимки — всё, что вы \
                вводите, — лежит в файлах приложения на самом телефоне. Там \
                же настройки.
                """)
            Paragraph("Фото и вопросы", body: """
                «Спросить о растении», «Спросить сад» и подсказки кличек \
                работают на \
                телефоне: фото разбирает Vision, тексты пишет Apple \
                Intelligence на самом iPhone. Ни фото, ни вопросы никуда не \
                отправляются.
                """)
            Paragraph("Погода", body: """
                Если включено «Учитывать погоду», примерное место телефона и \
                место дачи уходят в погоду Apple (WeatherKit) — узнать \
                погоду и дождь. Выключите — не уходит ничего.
                """)
            Paragraph("Геопозиция", body: """
                Точное место телефон узнаёт один раз — когда вы нажимаете \
                «Отметить дачу здесь», — и хранит у себя. О приезде на дачу \
                узнаёт сам iPhone.
                """)
            // Только в сборке с iCloud — см. `Kinship.enabled`.
            if Kinship.enabled {
                Paragraph("iCloud", body: """
                    Только если включить «Сад в iCloud»: сад — растения, \
                    снимки и журнал поливов — хранится и в вашем iCloud, а \
                    те, кого вы пригласили в общий сад, видят его в своём. \
                    Это iCloud Apple, а не сервер Sprout. Выключить — в \
                    профиле, в группе «Семья».
                    """)
            }
            Paragraph("Датчик движения", body: """
                Наклон телефона чуть двигает узор на фоне. Показания \
                используются только для этого, не сохраняются и никуда не \
                уходят.
                """)
            Paragraph("Уведомления", body: """
                Напоминания о поливе создаёт сам телефон по срокам, \
                посчитанным на нём же. Пуш-сервер в этом не участвует.
                """)
            Paragraph("Резервная копия", body: """
                Файл сада попадает в резервную копию iPhone — туда же, куда \
                и остальные ваши данные, по правилам Apple.
                """)
            Paragraph("Удаление", body: """
                Настройки → «Удалить все данные» стирает всё, что помнит \
                Sprout, — на телефоне и в вашем iCloud. Удалите приложение — \
                исчезнет то, что на телефоне.
                """)
        }
    }
}
